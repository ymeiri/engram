/// Result of one audit gate.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum AuditStatus {
    /// Required execution has not happened yet.
    Pending,
    /// The gate has deterministic passing evidence.
    Passed,
    /// Evidence exists but violates the frozen contract.
    Failed,
}

/// Current lifecycle state for one pilot lane.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum NativeLanePhase {
    /// No completed teaching trace exists.
    Prepared,
    /// Teaching completed; the matched Codex activation is still pending.
    AwaitingActivation,
    /// Teaching completed; trusted Engram verification is still pending.
    AwaitingVerification,
    /// A generated memory artifact is still pending.
    AwaitingArtifacts,
    /// Every pre-evaluation gate passed.
    ReadyForEvaluation,
    /// Evaluation produced a structurally valid outcome, which may pass or fail acceptance.
    EvaluationComplete,
    /// At least one integrity, lifecycle, or artifact invariant failed.
    Invalid,
}

/// Audit of one trace or trusted evaluator output file.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct FileAudit {
    /// Gate status.
    pub status: AuditStatus,
    /// Audited path.
    pub path: String,
    /// SHA-256 when a valid file exists.
    pub sha256: Option<String>,
    /// Last modification time in Unix milliseconds.
    pub modified_unix_ms: Option<u64>,
    /// Human-readable evidence or failure reason.
    pub detail: String,
}

/// Audit of a generated native-memory or Engram state artifact.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct ArtifactAudit {
    /// Owning memory layer.
    pub layer: String,
    /// Gate status.
    pub status: AuditStatus,
    /// Audited path.
    pub path: String,
    /// Stable digest over relative paths and file bytes.
    pub sha256: Option<String>,
    /// Number of regular files included in the digest.
    pub file_count: u64,
    /// Whether a non-empty generated artifact was observed.
    pub observed: bool,
    /// Human-readable evidence or failure reason.
    pub detail: String,
}

