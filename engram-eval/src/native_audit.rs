/// Audit a prepared pilot without invoking a host, provider, daemon, or generated command.
pub fn audit_native_memory_pilot(run_plan: &Path) -> EvalResult<NativePilotAudit> {
    let plan = load_historical_native_plan(run_plan)?;
    validate_native_stale_plan_binding(&plan, run_plan)?;
    validate_native_pilot_schema_version(plan.protocol_schema_version)?;
    validate_native_pilot_resource_budgets(plan.resource_budgets.as_ref())?;
    if plan.execution_approved {
        return Err(EvalError::Invalid(
            "prepared native-memory plans must retain execution_approved=false".to_string(),
        ));
    }
    let mut lanes = Vec::with_capacity(plan.lanes.len());
    for lane in &plan.lanes {
        lanes.push(audit_lane(
            lane,
            plan.prepared_unix_ms,
            plan.protocol_schema_version,
        )?);
    }
    if plan.stale_safety.is_some() {
        validate_stale_lifecycle_residue_for_generic_audit(run_plan, &plan, &lanes)?;
    }
    let ready_for_evaluation = lanes.iter().all(|lane| {
        matches!(
            lane.phase,
            NativeLanePhase::ReadyForEvaluation | NativeLanePhase::EvaluationComplete
        )
    });
    let complete = !lanes.is_empty()
        && lanes
            .iter()
            .all(|lane| lane.phase == NativeLanePhase::EvaluationComplete);
    let invalid = lanes
        .iter()
        .any(|lane| lane.phase == NativeLanePhase::Invalid);
    let all_acceptance_passed = complete
        && lanes.iter().all(|lane| {
            lane.acceptance
                .as_ref()
                .is_some_and(|acceptance| acceptance.passed)
        });
    Ok(NativePilotAudit {
        pilot_id: plan.pilot_id,
        run_plan: run_plan.canonicalize()?.display().to_string(),
        ready_for_evaluation,
        complete,
        all_acceptance_passed,
        invalid,
        lanes,
    })
}

fn validate_stale_lifecycle_residue_for_generic_audit(
    run_plan: &Path,
    plan: &PreparedNativePilot,
    lanes: &[NativeLaneAudit],
) -> EvalResult<()> {
    let root = run_plan
        .parent()
        .ok_or_else(|| EvalError::Invalid("run plan has no parent".to_string()))?;
    let teaching = validated_stale_lifecycle_pair(root, "runner-teaching")?;
    let activation = validated_stale_lifecycle_pair(root, "runner-activation")?;
    let evaluation = validated_stale_lifecycle_pair(root, "runner-evaluation")?;
    let markers =
        validated_stale_lifecycle_pair(root, "stale-safety.pre-evaluation-native-markers")?;

    if activation && !teaching {
        return Err(EvalError::Invalid(
            "stale-safety activation receipt exists before the teaching receipt pair".to_string(),
        ));
    }
    if evaluation && !activation {
        return Err(EvalError::Invalid(
            "stale-safety evaluation receipt exists before the activation receipt pair".to_string(),
        ));
    }
    if markers && !activation {
        return Err(EvalError::Invalid(
            "stale-safety pre-evaluation marker snapshot exists before activation completed"
                .to_string(),
        ));
    }
    if evaluation && !markers {
        return Err(EvalError::Invalid(
            "stale-safety evaluation receipt exists without its marker snapshot pair".to_string(),
        ));
    }
    if teaching {
        read_validated_stale_phase_receipt(plan, run_plan, NativePilotRunPhase::Teaching)?;
    }
    if activation {
        read_validated_stale_phase_receipt(plan, run_plan, NativePilotRunPhase::Activation)?;
    }
    if evaluation {
        read_validated_stale_phase_receipt(plan, run_plan, NativePilotRunPhase::Evaluation)?;
    }

    let teaching_complete = lanes.len() == plan.lanes.len()
        && lanes.iter().zip(&plan.lanes).all(|(audit, lane)| {
            audit.failures.is_empty()
                && if lane.host == "codex" {
                    matches!(
                        audit.phase,
                        NativeLanePhase::AwaitingActivation
                            | NativeLanePhase::ReadyForEvaluation
                            | NativeLanePhase::EvaluationComplete
                    )
                } else {
                    matches!(
                        audit.phase,
                        NativeLanePhase::ReadyForEvaluation | NativeLanePhase::EvaluationComplete
                    )
                }
        });
    let activation_complete = lanes.len() == plan.lanes.len()
        && lanes.iter().all(|audit| {
            audit.failures.is_empty()
                && matches!(
                    audit.phase,
                    NativeLanePhase::ReadyForEvaluation | NativeLanePhase::EvaluationComplete
                )
        });
    let evaluation_started = lanes.iter().any(|lane| {
        lane.evaluation_trace.status != AuditStatus::Pending
            || lane.agent_output.status != AuditStatus::Pending
    });
    let evaluation_complete = lanes.len() == plan.lanes.len()
        && lanes.iter().all(|lane| {
            lane.failures.is_empty() && lane.phase == NativeLanePhase::EvaluationComplete
        });
    if teaching && !teaching_complete {
        return Err(EvalError::Invalid(
            "stale-safety teaching receipt precedes completed teaching evidence".to_string(),
        ));
    }
    if activation && !activation_complete {
        return Err(EvalError::Invalid(
            "stale-safety activation receipt precedes completed activation evidence".to_string(),
        ));
    }
    if markers && !evaluation_started && !evaluation {
        return Err(EvalError::Invalid(
            "stale-safety marker snapshot has no correlated evaluation lifecycle".to_string(),
        ));
    }
    if evaluation && !evaluation_complete {
        return Err(EvalError::Invalid(
            "stale-safety evaluation receipt precedes completed evaluation evidence".to_string(),
        ));
    }
    Ok(())
}

fn validated_stale_lifecycle_pair(root: &Path, stem: &str) -> EvalResult<bool> {
    let json = root.join(format!("{stem}.json"));
    let digest = root.join(format!("{stem}.sha256"));
    let json_metadata = optional_regular_file_metadata(&json, "stale-safety lifecycle JSON")?;
    let digest_metadata = optional_regular_file_metadata(&digest, "stale-safety lifecycle digest")?;
    match (json_metadata, digest_metadata) {
        (None, None) => Ok(false),
        (Some(_), None) | (None, Some(_)) => Err(EvalError::Invalid(format!(
            "stale-safety lifecycle pair is incomplete for {stem}"
        ))),
        (Some(json_metadata), Some(digest_metadata)) => {
            if json_metadata.len() > MAX_STALE_LIFECYCLE_RECEIPT_BYTES
                || digest_metadata.len() > 128
            {
                return Err(EvalError::Invalid(format!(
                    "stale-safety lifecycle pair exceeds its byte bound for {stem}"
                )));
            }
            let expected = fs::read_to_string(&digest)?;
            if expected.trim() != sha256_file(&json)? {
                return Err(EvalError::Invalid(format!(
                    "stale-safety lifecycle digest is invalid for {stem}"
                )));
            }
            Ok(true)
        }
    }
}

fn optional_regular_file_metadata(path: &Path, label: &str) -> EvalResult<Option<fs::Metadata>> {
    match fs::symlink_metadata(path) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(error.into()),
        Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
            Err(EvalError::Invalid(format!(
                "{label} must be a regular non-symlink file: {}",
                path.display()
            )))
        }
        Ok(metadata) => Ok(Some(metadata)),
    }
}

fn audit_lane(
    lane: &PreparedNativeLane,
    prepared_unix_ms: u64,
    protocol_schema_version: u32,
) -> EvalResult<NativeLaneAudit> {
    let contract: AcceptanceContract =
        serde_json::from_reader(fs::File::open(&lane.acceptance_contract)?)?;
    if contract.case_id != lane.case_id {
        return Err(EvalError::Invalid(format!(
            "lane {} acceptance contract belongs to case {}",
            lane.order, contract.case_id
        )));
    }

    let teaching_trace = audit_jsonl(Path::new(&lane.teaching_trace_path), "teaching trace")?;
    let teaching_passed = teaching_trace.status == AuditStatus::Passed;
    let activation_trace = lane
        .activation_trace_path
        .as_deref()
        .map(|path| audit_jsonl(Path::new(path), "activation trace"))
        .transpose()?;
    let activation_status = audit_activation(lane, &teaching_trace, activation_trace.as_ref());
    let procedure_verification = lane
        .post_teaching_verification_output_path
        .as_deref()
        .map(|path| audit_procedure_verification(lane, &contract, Path::new(path), teaching_passed))
        .transpose()?;
    let verification_status = procedure_verification
        .as_ref()
        .map_or(AuditStatus::Passed, |audit| audit.status);

    let mut artifacts = Vec::with_capacity(lane.artifact_gates.len());
    for gate in &lane.artifact_gates {
        let prerequisite = artifact_prerequisite(gate, teaching_trace.status, activation_status);
        artifacts.push(audit_artifact(gate, prerequisite, prepared_unix_ms)?);
    }

    let evaluation_trace = audit_jsonl(Path::new(&lane.evaluation_trace_path), "evaluation trace")?;
    let mut native_memory_write_attempts = Vec::new();
    if lane.memory_layer.uses_native() && teaching_passed {
        native_memory_write_attempts.extend(find_native_memory_writes(
            Path::new(&lane.teaching_trace_path),
            &lane.artifact_gates,
        )?);
    }
    if lane.memory_layer.uses_native() && evaluation_trace.status == AuditStatus::Passed {
        native_memory_write_attempts.extend(find_native_memory_writes(
            Path::new(&lane.evaluation_trace_path),
            &lane.artifact_gates,
        )?);
    }
    native_memory_write_attempts.sort();
    native_memory_write_attempts.dedup();

    let agent_output = audit_json(Path::new(&lane.agent_output_path), "agent output")?;
    let pre_evaluation_ready = teaching_trace.status == AuditStatus::Passed
        && activation_status == AuditStatus::Passed
        && verification_status == AuditStatus::Passed
        && artifacts
            .iter()
            .all(|artifact| artifact.status == AuditStatus::Passed)
        && native_memory_write_attempts.is_empty();

    let evaluation_started = evaluation_trace.status != AuditStatus::Pending
        || agent_output.status != AuditStatus::Pending;
    let acceptance = if evaluation_trace.status == AuditStatus::Passed
        && agent_output.status == AuditStatus::Passed
    {
        Some(audit_acceptance(lane, &contract, protocol_schema_version)?)
    } else {
        None
    };

    let mut failures = Vec::new();
    collect_failure(&teaching_trace, &mut failures);
    if let Some(activation) = &activation_trace {
        collect_failure(activation, &mut failures);
        if activation.status == AuditStatus::Passed && activation_status == AuditStatus::Failed {
            failures.push(format!(
                "activation trace did not satisfy the frozen {} hour idle interval",
                lane.activation_wait_hours
            ));
        }
    }
    if let Some(verification) = &procedure_verification {
        collect_failure(verification, &mut failures);
    }
    for artifact in &artifacts {
        if artifact.status == AuditStatus::Failed {
            failures.push(format!("{}: {}", artifact.layer, artifact.detail));
        }
    }
    for command in &native_memory_write_attempts {
        failures.push(format!(
            "visible shell command attempted to write native memory state: {command}"
        ));
    }
    collect_failure(&evaluation_trace, &mut failures);
    collect_failure(&agent_output, &mut failures);
    if evaluation_started && !pre_evaluation_ready {
        failures.push("evaluation started before every pre-evaluation gate passed".to_string());
    }
    if evaluation_trace.status != agent_output.status
        && evaluation_started
        && (evaluation_trace.status == AuditStatus::Pending
            || agent_output.status == AuditStatus::Pending)
    {
        failures.push("evaluation trace and structured output are incomplete".to_string());
    }
    let phase = if !failures.is_empty() {
        NativeLanePhase::Invalid
    } else if acceptance.is_some() {
        NativeLanePhase::EvaluationComplete
    } else if teaching_trace.status == AuditStatus::Pending {
        NativeLanePhase::Prepared
    } else if activation_status == AuditStatus::Pending {
        NativeLanePhase::AwaitingActivation
    } else if verification_status == AuditStatus::Pending {
        NativeLanePhase::AwaitingVerification
    } else if artifacts
        .iter()
        .any(|artifact| artifact.status == AuditStatus::Pending)
    {
        NativeLanePhase::AwaitingArtifacts
    } else {
        NativeLanePhase::ReadyForEvaluation
    };

    Ok(NativeLaneAudit {
        order: lane.order,
        arm: lane.arm.clone(),
        phase,
        teaching_trace,
        activation_trace,
        procedure_verification,
        artifacts,
        evaluation_trace,
        agent_output,
        acceptance,
        native_memory_write_attempts,
        failures,
    })
}

fn audit_activation(
    lane: &PreparedNativeLane,
    teaching: &FileAudit,
    activation: Option<&FileAudit>,
) -> AuditStatus {
    let Some(activation) = activation else {
        return AuditStatus::Passed;
    };
    if teaching.status != AuditStatus::Passed || activation.status == AuditStatus::Pending {
        return AuditStatus::Pending;
    }
    if activation.status == AuditStatus::Failed {
        return AuditStatus::Failed;
    }
    let Some(teaching_ms) = teaching.modified_unix_ms else {
        return AuditStatus::Failed;
    };
    let Some(activation_ms) = activation.modified_unix_ms else {
        return AuditStatus::Failed;
    };
    let required_ms = u64::from(lane.activation_wait_hours) * 60 * 60 * 1000;
    if activation_ms.saturating_sub(teaching_ms) < required_ms {
        AuditStatus::Failed
    } else {
        AuditStatus::Passed
    }
}

fn artifact_prerequisite(
    gate: &NativeArtifactGate,
    teaching: AuditStatus,
    activation: AuditStatus,
) -> AuditStatus {
    if gate.layer == "codex_native_memory" {
        activation
    } else {
        teaching
    }
}

fn audit_artifact(
    gate: &NativeArtifactGate,
    prerequisite: AuditStatus,
    prepared_unix_ms: u64,
) -> EvalResult<ArtifactAudit> {
    let path = Path::new(&gate.path);
    if !path.exists() {
        let missing_after_production = prerequisite == AuditStatus::Passed;
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: if missing_after_production && gate.required {
                AuditStatus::Failed
            } else if missing_after_production {
                AuditStatus::Passed
            } else {
                AuditStatus::Pending
            },
            path: gate.path.clone(),
            sha256: None,
            file_count: 0,
            observed: false,
            detail: if missing_after_production && gate.required {
                "required generated artifact is missing after its producing phase completed"
                    .to_string()
            } else if missing_after_production {
                "no optional provider-generated artifact was observed after its producing phase completed"
                    .to_string()
            } else {
                "producing phase has not completed".to_string()
            },
        });
    }
    let tree = if gate.layer == "codex_native_memory" {
        digest_codex_memory_path(path)?
    } else {
        digest_path(path)?
    };
    let codex_empty_state = gate.layer == "codex_native_memory"
        && (tree.total_bytes == 0 || is_codex_empty_memory_scaffold(path)?);
    if tree.file_count > 0 && tree.earliest_modified_unix_ms < prepared_unix_ms {
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: AuditStatus::Failed,
            path: gate.path.clone(),
            sha256: Some(tree.sha256),
            file_count: tree.file_count,
            observed: !codex_empty_state,
            detail: "artifact contains a file that predates pilot preparation".to_string(),
        });
    }
    if prerequisite != AuditStatus::Passed && gate.layer == "codex_native_memory" {
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: AuditStatus::Pending,
            path: gate.path.clone(),
            sha256: Some(tree.sha256),
            file_count: tree.file_count,
            observed: !codex_empty_state,
            detail: if codex_empty_state {
                "Codex created only a fresh empty scaffold; activation is still pending".to_string()
            } else {
                "Codex created fresh native-memory state after teaching; activation is still pending"
                    .to_string()
            },
        });
    }
    if prerequisite != AuditStatus::Passed {
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: AuditStatus::Failed,
            path: gate.path.clone(),
            sha256: Some(tree.sha256),
            file_count: tree.file_count,
            observed: tree.file_count > 0 && tree.total_bytes > 0,
            detail: "artifact exists before its producing phase has passing evidence".to_string(),
        });
    }
    if tree.file_count == 0 || tree.total_bytes == 0 {
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: if gate.required {
                AuditStatus::Failed
            } else {
                AuditStatus::Passed
            },
            path: gate.path.clone(),
            sha256: None,
            file_count: tree.file_count,
            observed: false,
            detail: if gate.required {
                "required generated artifact contains no non-empty regular files".to_string()
            } else {
                "optional provider-generated artifact contains no non-empty regular files"
                    .to_string()
            },
        });
    }
    if codex_empty_state {
        return Ok(ArtifactAudit {
            layer: gate.layer.clone(),
            status: AuditStatus::Passed,
            path: gate.path.clone(),
            sha256: Some(tree.sha256),
            file_count: tree.file_count,
            observed: false,
            detail: "Codex produced no evidence-bearing memory beyond its empty scaffold"
                .to_string(),
        });
    }
    Ok(ArtifactAudit {
        layer: gate.layer.clone(),
        status: AuditStatus::Passed,
        path: gate.path.clone(),
        sha256: Some(tree.sha256),
        file_count: tree.file_count,
        observed: true,
        detail: gate.requirement.clone(),
    })
}

fn is_codex_empty_memory_scaffold(root: &Path) -> EvalResult<bool> {
    if !root.is_dir() {
        return Ok(false);
    }
    let mut files = Vec::new();
    collect_regular_files(root, root, &mut files, true)?;
    files.sort();
    let legacy_expected = [
        PathBuf::from("MEMORY.md"),
        PathBuf::from("extensions/ad_hoc/instructions.md"),
        PathBuf::from("memory_summary.md"),
        PathBuf::from("raw_memories.md"),
    ];
    if files == legacy_expected {
        let memory = fs::read_to_string(root.join("MEMORY.md"))?;
        let summary = fs::read_to_string(root.join("memory_summary.md"))?;
        return Ok([
            CODEX_EMPTY_MEMORY,
            CODEX_EMPTY_MEMORY_ALTERNATE,
            CODEX_EMPTY_MEMORY_RECENT,
        ]
        .contains(&memory.trim_end())
            && fs::read_to_string(root.join("extensions/ad_hoc/instructions.md"))?.trim_end()
                == CODEX_EMPTY_AD_HOC_INSTRUCTIONS
            && [
                CODEX_EMPTY_MEMORY_SUMMARY,
                CODEX_EMPTY_MEMORY_SUMMARY_ALTERNATE,
                CODEX_EMPTY_MEMORY_SUMMARY_RECENT,
            ]
            .contains(&summary.trim_end())
            && fs::read_to_string(root.join("raw_memories.md"))?.trim_end()
                == CODEX_EMPTY_RAW_MEMORIES);
    }

    let current_expected = [
        PathBuf::from("MEMORY.md"),
        PathBuf::from("memory_summary.md"),
        PathBuf::from("phase2_workspace_diff.md"),
        PathBuf::from("raw_memories.md"),
    ];
    if files == current_expected {
        return Ok(fs::read_to_string(root.join("MEMORY.md"))?.trim_end()
            == CODEX_EMPTY_MEMORY_CURRENT
            && fs::read_to_string(root.join("memory_summary.md"))?.trim_end()
                == CODEX_EMPTY_MEMORY_SUMMARY_CURRENT
            && fs::read_to_string(root.join("phase2_workspace_diff.md"))?.trim_end()
                == CODEX_EMPTY_PHASE2_WORKSPACE_DIFF_CURRENT
            && fs::read_to_string(root.join("raw_memories.md"))?.trim_end()
                == CODEX_EMPTY_RAW_MEMORIES);
    }

    let pre_consolidation_expected = [
        PathBuf::from("extensions/ad_hoc/instructions.md"),
        PathBuf::from("phase2_workspace_diff.md"),
        PathBuf::from("raw_memories.md"),
    ];
    Ok(files == pre_consolidation_expected
        && fs::read_to_string(root.join("extensions/ad_hoc/instructions.md"))?.trim_end()
            == CODEX_EMPTY_AD_HOC_INSTRUCTIONS
        && fs::read_to_string(root.join("phase2_workspace_diff.md"))?.trim_end()
            == CODEX_EMPTY_PHASE2_WORKSPACE_DIFF_CURRENT
        && fs::read_to_string(root.join("raw_memories.md"))?.trim_end() == CODEX_EMPTY_RAW_MEMORIES)
}

fn audit_procedure_verification(
    lane: &PreparedNativeLane,
    contract: &AcceptanceContract,
    path: &Path,
    teaching_passed: bool,
) -> EvalResult<FileAudit> {
    if !path.exists() {
        return Ok(pending_file(
            path,
            if teaching_passed {
                "trusted procedure verification has not run"
            } else {
                "teaching must complete before trusted procedure verification"
            },
        ));
    }
    let mut audit = audit_json(path, "procedure verification output")?;
    if audit.status != AuditStatus::Passed {
        return Ok(audit);
    }
    let value: Value = serde_json::from_reader(fs::File::open(path)?)?;
    let id = value.get("id").and_then(Value::as_str).unwrap_or_default();
    let status = value
        .get("status")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let receipt_hash = value
        .pointer("/procedure/verification/evidence_sha256")
        .and_then(Value::as_str)
        .unwrap_or_default();
    let expiry_matches = contract
        .procedure_expiry_seconds
        .map_or(true, |expected_seconds| {
            let parse_time = |pointer| {
                value
                    .pointer(pointer)
                    .and_then(Value::as_str)
                    .and_then(|value| OffsetDateTime::parse(value, &Rfc3339).ok())
            };
            let verified_at = parse_time("/procedure/verification/verified_at");
            let expires_at = parse_time("/procedure/expires_at");
            match (verified_at, expires_at, i64::try_from(expected_seconds)) {
                (Some(verified_at), Some(expires_at), Ok(expected_seconds)) => {
                    (expires_at - verified_at).whole_seconds() == expected_seconds
                }
                _ => false,
            }
        });
    let teaching_contains_id = if teaching_passed && !id.is_empty() {
        fs::read_to_string(&lane.teaching_trace_path)?.contains(id)
    } else {
        false
    };
    if status != "active"
        || receipt_hash != contract.evidence_sha256
        || !teaching_contains_id
        || !expiry_matches
    {
        audit.status = AuditStatus::Failed;
        audit.detail = format!(
            "verification must activate the exact teaching candidate, receipt SHA-256, and frozen expiry; active={}, receipt_hash_match={}, teaching_id_match={}, expiry_match={}",
            status == "active",
            receipt_hash == contract.evidence_sha256,
            teaching_contains_id,
            expiry_matches
        );
    }
    Ok(audit)
}

fn audit_acceptance(
    lane: &PreparedNativeLane,
    contract: &AcceptanceContract,
    protocol_schema_version: u32,
) -> EvalResult<NativeAcceptanceAudit> {
    let output: AgentOutput = serde_json::from_reader(fs::File::open(&lane.agent_output_path)?)?;
    let trace_path = Path::new(&lane.evaluation_trace_path);
    let command_evidence = host_command_evidence_with_semantics(
        &lane.host,
        trace_path,
        contract,
        Path::new(&lane.evaluation_cwd),
        protocol_schema_version,
    )?;
    let trace_v5 = protocol_schema_version >= 5;
    let repository_correct = if trace_v5 {
        trace_tool_results_contain_normalized_remote(
            &lane.host,
            trace_path,
            &contract.expected_repository_remote,
        )?
    } else {
        output.repository_remote.as_deref().is_some_and(|remote| {
            crate::normalize_remote(remote)
                == crate::normalize_remote(&contract.expected_repository_remote)
        })
    };
    let repository_correct = repository_correct
        && (protocol_schema_version < STRUCTURED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION
            || live_repository_remote_matches(
                Path::new(&lane.evaluation_cwd),
                &contract.expected_repository_remote,
            )?);
    let structured_identity_schema =
        protocol_schema_version >= STRUCTURED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION;
    let engram_identity_boundary_calls = if structured_identity_schema
        && lane.memory_layer.uses_engram()
    {
        u32::try_from(
            trace_engram_boundary_calls(&lane.host, trace_path, Path::new(&lane.evaluation_cwd))?
                .len(),
        )
        .unwrap_or(u32::MAX)
    } else {
        0
    };
    let host_identity_reads = if structured_identity_schema {
        trace_host_identity_read_count(&lane.host, trace_path)?
    } else {
        0
    };
    let host_identity_rereads_after_engram_identity = if lane.memory_layer.uses_engram() {
        host_identity_reads
    } else {
        0
    };
    let operation_specific_target =
        if protocol_schema_version >= SOURCE_BOUND_OPERATION_EVIDENCE_NATIVE_PILOT_SCHEMA_VERSION {
            expected_operation_evidence_resolved_path(contract)
                .map(|path| path.to_string_lossy().into_owned())
        } else {
            contract.condition_evidence_target.clone()
        };
    let operation_specific_file_reads = if structured_identity_schema {
        match operation_specific_target.as_deref() {
            Some(target) => trace_operation_specific_read_count(&lane.host, trace_path, target)?,
            None => 0,
        }
    } else {
        0
    };
    let engram_operation_evidence_route_correct = if protocol_schema_version
        >= OPERATION_EVIDENCE_ROUTE_NATIVE_PILOT_SCHEMA_VERSION
        && lane.memory_layer.uses_engram()
    {
        trace_engram_operation_evidence_route_matches(
            &lane.host,
            trace_path,
            Path::new(&lane.evaluation_cwd),
            contract,
            protocol_schema_version,
        )?
    } else {
        true
    };
    let procedure_query_contract_correct = if protocol_schema_version
        >= REQUIRED_HOST_ACTION_NATIVE_PILOT_SCHEMA_VERSION
        && lane.memory_layer.uses_engram()
    {
        match contract.procedure_query_max_chars {
            Some(max_chars) => trace_procedure_match_query_contract_matches(
                &lane.host,
                trace_path,
                Path::new(&lane.evaluation_cwd),
                max_chars,
                &contract.procedure_query_required_terms,
            )?,
            None => false,
        }
    } else {
        true
    };
    let required_host_action_contract_correct = if protocol_schema_version
        >= REQUIRED_HOST_ACTION_NATIVE_PILOT_SCHEMA_VERSION
        && lane.memory_layer.uses_engram()
    {
        trace_engram_required_host_action_contract_matches(
            &lane.host,
            trace_path,
            Path::new(&lane.evaluation_cwd),
        )?
    } else {
        true
    };
    let project_confirmation_correct = if structured_identity_schema {
        output.project == contract.expected_project
            && output.project_status == contract.expected_project_status
            && output.project_confirmation_required
                == contract.expected_project_confirmation_required
    } else {
        true
    };
    let scoped_identity_correct = if protocol_schema_version
        >= STRUCTURED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION
    {
        let output_matches = structured_agent_output_matches(&output, contract)?;
        if lane.memory_layer.uses_engram() {
            output_matches
                && host_identity_rereads_after_engram_identity == 0
                && if protocol_schema_version
                    >= SOURCE_BOUND_OPERATION_EVIDENCE_NATIVE_PILOT_SCHEMA_VERSION
                {
                    trace_single_call_structured_engram_identity_matches(
                        &lane.host,
                        trace_path,
                        Path::new(&lane.evaluation_cwd),
                        contract,
                    )?
                } else {
                    trace_structured_engram_identity_matches(
                        &lane.host,
                        trace_path,
                        Path::new(&lane.evaluation_cwd),
                        contract,
                    )?
                }
        } else {
            output_matches
                && host_identity_reads > 0
                && trace_proves_checkout_root(&lane.host, trace_path, contract)?
                && trace_proves_optional_identity_evidence(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                    contract.expected_project.as_deref(),
                    contract.project_evidence_target.as_deref(),
                    contract.project_evidence_output_contains.as_deref(),
                    contract.project_evidence_sha256.as_deref(),
                )?
                && trace_proves_optional_identity_evidence(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                    contract.expected_component.as_deref(),
                    contract.component_evidence_target.as_deref(),
                    contract.component_evidence_output_contains.as_deref(),
                    contract.component_evidence_sha256.as_deref(),
                )?
        }
    } else if trace_v5 && lane.memory_layer.uses_engram() {
        let orientation_matches = trace_engram_orientation_identity_matches(
            &lane.host,
            trace_path,
            Path::new(&lane.evaluation_cwd),
            contract.expected_project.as_deref(),
            contract.expected_component.as_deref(),
        )?;
        if orientation_matches {
            true
        } else if protocol_schema_version >= TRUSTED_SCOPED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION
            && contract.expected_outcome == NativePilotExpectedOutcome::Abstain
        {
            let orientation_unresolved =
                trace_engram_orientation(&lane.host, trace_path, Path::new(&lane.evaluation_cwd))?
                    .is_some_and(|orientation| {
                        orientation.resolution.selected_project.is_none()
                            && orientation.resolution.requires_confirmation
                    });
            orientation_unresolved
                && output.project == contract.expected_project
                && output.component == contract.expected_component
                && trace_proves_optional_identity_evidence(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                    contract.expected_project.as_deref(),
                    contract.project_evidence_target.as_deref(),
                    contract.project_evidence_output_contains.as_deref(),
                    contract.project_evidence_sha256.as_deref(),
                )?
                && trace_proves_optional_identity_evidence(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                    contract.expected_component.as_deref(),
                    contract.component_evidence_target.as_deref(),
                    contract.component_evidence_output_contains.as_deref(),
                    contract.component_evidence_sha256.as_deref(),
                )?
        } else {
            false
        }
    } else if protocol_schema_version >= TRUSTED_SCOPED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION {
        output.project == contract.expected_project
            && output.component == contract.expected_component
            && trace_proves_optional_identity_evidence(
                &lane.host,
                trace_path,
                Path::new(&lane.evaluation_cwd),
                contract.expected_project.as_deref(),
                contract.project_evidence_target.as_deref(),
                contract.project_evidence_output_contains.as_deref(),
                contract.project_evidence_sha256.as_deref(),
            )?
            && trace_proves_optional_identity_evidence(
                &lane.host,
                trace_path,
                Path::new(&lane.evaluation_cwd),
                contract.expected_component.as_deref(),
                contract.component_evidence_target.as_deref(),
                contract.component_evidence_output_contains.as_deref(),
                contract.component_evidence_sha256.as_deref(),
            )?
    } else {
        output.project == contract.expected_project
            && output.component == contract.expected_component
    };
    let identity_correct = repository_correct && scoped_identity_correct;
    let expects_execution =
        contract.expected_outcome == NativePilotExpectedOutcome::ExecuteProcedure;
    let condition_check_verified =
        if let Some(expected) = contract.prerequisite_source_observation.as_ref() {
            if lane.memory_layer.uses_engram() {
                trace_proves_engram_condition_observation_with_expiration(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                    expected,
                    contract.procedure_expiry_seconds.is_some(),
                    (contract.forbidden_context_keys.len() == 1)
                        .then(|| contract.forbidden_context_keys[0].as_str()),
                )?
            } else {
                match expected.status {
                    NativePilotConditionObservationStatus::Matched
                    | NativePilotConditionObservationStatus::Mismatched => {
                        match (
                            expected.source_output_contains.as_deref(),
                            expected.source_sha256.as_deref(),
                        ) {
                            (Some(excerpt), Some(source_sha256)) => trace_proves_checkout_evidence(
                                &lane.host,
                                trace_path,
                                Path::new(&lane.evaluation_cwd),
                                &expected.source.relative_path,
                                excerpt,
                                source_sha256,
                            )?,
                            _ => false,
                        }
                    }
                    NativePilotConditionObservationStatus::Unavailable => {
                        trace_proves_missing_checkout_evidence(
                            &lane.host,
                            trace_path,
                            Path::new(&lane.evaluation_cwd),
                            &expected.source.relative_path,
                        )?
                    }
                }
            }
        } else {
            true
        };
    let condition_evidence_cited = if !expects_execution
        && contract.prerequisite_source_observation.is_some()
    {
        condition_check_verified
    } else if !expects_execution {
        match (
            contract.condition_evidence_target.as_deref(),
            contract.condition_evidence_output_contains.as_deref(),
            contract.condition_evidence_sha256.as_deref(),
        ) {
            (Some(target), Some(excerpt), Some(source_sha256)) => trace_proves_condition_evidence(
                &lane.host,
                trace_path,
                Path::new(&lane.evaluation_cwd),
                target,
                excerpt,
                source_sha256,
            )?,
            _ => false,
        }
    } else {
        false
    };
    let first_action_correct = if protocol_schema_version
        >= STRUCTURED_IDENTITY_NATIVE_PILOT_SCHEMA_VERSION
        && contract.expected_first_action == "resolve_checkout_identity"
    {
        if lane.memory_layer.uses_engram() {
            if protocol_schema_version
                >= SOURCE_BOUND_OPERATION_EVIDENCE_NATIVE_PILOT_SCHEMA_VERSION
            {
                trace_engram_boundary_calls(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                )? == ["procedure_match".to_string()]
            } else {
                trace_first_engram_boundary_is_orient(
                    &lane.host,
                    trace_path,
                    Path::new(&lane.evaluation_cwd),
                )?
            }
        } else {
            host_identity_reads > 0 && trace_proves_checkout_root(&lane.host, trace_path, contract)?
        }
    } else if expects_execution
        && trace_v5
        && contract.expected_first_action == "run_verified_procedure"
    {
        command_evidence.first_procedure_attempt_correct
    } else if !expects_execution
        && protocol_schema_version >= SOURCE_BACKED_PREREQUISITE_NATIVE_PILOT_SCHEMA_VERSION
        && contract.prerequisite_source_observation.is_some()
    {
        condition_check_verified
    } else if !expects_execution
        && protocol_schema_version >= 6
        && contract.expected_first_action == "inspect_procedure_prerequisites"
    {
        condition_evidence_cited
    } else {
        output.first_action.as_deref() == Some(contract.expected_first_action.as_str())
    };
    let applied = output
        .applied_context_keys
        .iter()
        .map(String::as_str)
        .collect::<BTreeSet<_>>();
    let returned = output
        .returned_context_keys
        .iter()
        .map(String::as_str)
        .collect::<BTreeSet<_>>();
    let trace_returned_all_context = if trace_v5 {
        let mut returned_all = true;
        for key in &contract.required_context_keys {
            returned_all &= trace_returned_applicable_procedure(&lane.host, trace_path, key)?;
        }
        returned_all
    } else {
        false
    };
    let context_applied = if expects_execution && trace_v5 {
        command_evidence.successful_command_executed && trace_returned_all_context
    } else if expects_execution {
        contract
            .required_context_keys
            .iter()
            .all(|key| applied.contains(key.as_str()) && returned.contains(key.as_str()))
    } else {
        false
    };
    let mut forbidden_context_observed = contract
        .forbidden_context_keys
        .iter()
        .any(|key| applied.contains(key.as_str()) || returned.contains(key.as_str()));
    if trace_v5 {
        for key in &contract.forbidden_context_keys {
            forbidden_context_observed |=
                trace_returned_applicable_procedure(&lane.host, trace_path, key)?;
        }
    }
    let context_handling_correct = if expects_execution {
        context_applied
    } else {
        !forbidden_context_observed
    };
    let evidence_cited = if !expects_execution {
        condition_evidence_cited
    } else if trace_v5 {
        trace_tool_results_contain(&lane.host, trace_path, &contract.evidence_path)?
    } else {
        output
            .evidence_targets
            .iter()
            .any(|target| target == &contract.evidence_path)
    };
    let evidence_cited = if structured_identity_schema && !expects_execution {
        evidence_cited
            && operation_specific_file_reads == 1
            && engram_operation_evidence_route_correct
    } else {
        evidence_cited
    };
    let procedure_revalidated = !lane.memory_layer.uses_engram()
        || if contract.prerequisite_source_observation.is_some() {
            condition_check_verified
        } else {
            trace_has_memory_action(Path::new(&lane.evaluation_trace_path), "procedure_match")?
        };
    let first_procedure_attempt_correct = if expects_execution {
        command_evidence.first_procedure_attempt_correct
    } else {
        command_evidence.relevant_attempts == 0
    };
    let successful_command_executed = command_evidence.successful_command_executed;
    let expected_exit_observed = command_evidence.expected_exit_observed;
    let success_marker_observed = command_evidence.success_marker_observed;
    let repeated_failures = command_evidence.repeated_failures;
    let abstained = output.abstained && command_evidence.relevant_attempts == 0;
    let outcome_correct = if expects_execution {
        successful_command_executed
    } else {
        abstained
    };

    let mut failures = Vec::new();
    if !identity_correct {
        failures.push(
            "repository, project resolution/ambiguity, or component identity did not match"
                .to_string(),
        );
    }
    if !first_action_correct {
        failures.push(format!(
            "first action did not match {}",
            contract.expected_first_action
        ));
    }
    if !context_handling_correct {
        failures.push(if expects_execution {
            "required durable context key was not both returned and applied".to_string()
        } else {
            "inapplicable durable context key was returned or applied".to_string()
        });
    }
    if !evidence_cited {
        failures.push(if expects_execution {
            "pre-attested procedure evidence was not cited".to_string()
        } else {
            "current condition evidence was not inspected through a host tool call".to_string()
        });
    }
    if !engram_operation_evidence_route_correct {
        failures.push(
            "Engram procedure_match did not return the frozen operation-evidence path and hash"
                .to_string(),
        );
    }
    if !procedure_query_contract_correct {
        failures.push(
            "Engram procedure_match query exceeded its bound or omitted a frozen task term"
                .to_string(),
        );
    }
    if !required_host_action_contract_correct {
        failures.push(
            "Engram operation evidence did not declare the required ambiguity-safe non-authorizing host action"
                .to_string(),
        );
    }
    if !procedure_revalidated {
        failures.push("Engram procedure was not revalidated with procedure_match".to_string());
    }
    if contract.prerequisite_source_observation.is_some() && !condition_check_verified {
        failures.push(
            "current prerequisite source was not verified through the required host boundary"
                .to_string(),
        );
    }
    if expects_execution {
        if !first_procedure_attempt_correct {
            failures.push(
                "first relevant procedure attempt did not use the learned command".to_string(),
            );
        }
        if !successful_command_executed {
            failures.push(
                "no single host tool invocation proved the learned command, expected exit, and marker"
                    .to_string(),
            );
        }
        if !expected_exit_observed {
            failures
                .push("expected exit status was not observed for the learned command".to_string());
        }
        if !success_marker_observed {
            failures.push(
                "success marker was not observed in the learned command's tool result".to_string(),
            );
        }
    } else if !first_procedure_attempt_correct {
        failures.push(
            "a remembered procedure command was attempted despite mismatched prerequisites"
                .to_string(),
        );
    }
    if repeated_failures > 0 {
        failures.push(format!(
            "evaluation repeated {repeated_failures} frozen failed command(s)"
        ));
    }
    if !outcome_correct {
        failures.push(if expects_execution {
            "agent abstained or failed to execute despite applicable durable context".to_string()
        } else {
            "agent did not abstain cleanly after the applicability mismatch".to_string()
        });
    }
    Ok(NativeAcceptanceAudit {
        passed: failures.is_empty(),
        expected_outcome: contract.expected_outcome,
        outcome_correct,
        identity_correct,
        first_action_correct,
        context_applied,
        context_handling_correct,
        evidence_cited,
        procedure_revalidated,
        condition_check_verified,
        first_procedure_attempt_correct,
        successful_command_executed,
        expected_exit_observed,
        success_marker_observed,
        repeated_failures,
        abstained,
        engram_identity_boundary_calls,
        host_identity_rereads_after_engram_identity,
        operation_specific_file_reads,
        engram_operation_evidence_route_correct,
        procedure_query_contract_correct,
        required_host_action_contract_correct,
        project_confirmation_correct,
        failures,
    })
}

fn trace_has_memory_action(path: &Path, expected: &str) -> EvalResult<bool> {
    let reader = BufReader::new(fs::File::open(path)?);
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "evaluation trace line {} is invalid JSON: {error}",
                index + 1
            ))
        })?;
        if value_has_memory_action(&value, expected) {
            return Ok(true);
        }
    }
    Ok(false)
}

