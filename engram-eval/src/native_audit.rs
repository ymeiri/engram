fn trace_engram_orientation_identity_matches(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    expected_project: Option<&str>,
    expected_component: Option<&str>,
) -> EvalResult<bool> {
    let Some(orientation) = trace_engram_orientation(host, path, evaluation_cwd)? else {
        return Ok(false);
    };
    let resolution = orientation.resolution;
    let project_matches = match expected_project {
        Some(project) => {
            resolution.selected_project.as_deref() == Some(project)
                && !resolution.requires_confirmation
        }
        None => resolution.selected_project.is_none() && resolution.requires_confirmation,
    };
    if !project_matches {
        return Ok(false);
    }
    let Some(expected_component) = expected_component else {
        return Ok(
            resolution.component_names.is_empty() && resolution.component_evidence.is_empty()
        );
    };
    if resolution.component_names.first().map(String::as_str) != Some(expected_component) {
        return Ok(false);
    }
    let Some(evidence) = resolution
        .component_evidence
        .iter()
        .find(|evidence| evidence.name == expected_component)
    else {
        return Ok(false);
    };
    verify_component_evidence(evaluation_cwd, evidence)
}

