fn trace_procedure_match_query_contract_matches(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    max_chars: u32,
    required_terms: &[String],
) -> EvalResult<bool> {
    let queries = trace_procedure_match_queries(host, path, evaluation_cwd)?;
    let Some(query) = queries.first().filter(|_| queries.len() == 1) else {
        return Ok(false);
    };
    let normalized = query.trim().to_ascii_lowercase();
    Ok(!normalized.is_empty()
        && query.chars().count() <= max_chars as usize
        && required_terms
            .iter()
            .all(|term| normalized.contains(&term.trim().to_ascii_lowercase())))
}

fn trace_procedure_match_queries(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
) -> EvalResult<Vec<String>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut queries = Vec::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        match host {
            "codex" => {
                let Some(item) = value.get("item") else {
                    continue;
                };
                let arguments = item.get("arguments").unwrap_or(&Value::Null);
                if value.get("type").and_then(Value::as_str) == Some("item.completed")
                    && item.get("type").and_then(Value::as_str) == Some("mcp_tool_call")
                    && item.get("server").and_then(Value::as_str) == Some("engram")
                    && item.get("tool").and_then(Value::as_str) == Some("memory")
                    && (item.get("error").is_none()
                        || item.get("error").is_some_and(Value::is_null))
                    && is_procedure_match_action(arguments.get("action").and_then(Value::as_str))
                    && memory_call_targets_cwd(arguments, evaluation_cwd)
                {
                    if let Some(query) = arguments.get("query").and_then(Value::as_str) {
                        queries.push(query.to_string());
                    }
                }
            }
            "claude_code" => {
                collect_claude_procedure_match_queries(&value, evaluation_cwd, &mut queries)
            }
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in procedure-query audit: {other}"
                )))
            }
        }
    }
    Ok(queries)
}

fn collect_claude_procedure_match_queries(
    value: &Value,
    evaluation_cwd: &Path,
    queries: &mut Vec<String>,
) {
    match value {
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("tool_use")
                && object.get("name").and_then(Value::as_str) == Some("mcp__engram__memory")
            {
                let input = object.get("input").unwrap_or(&Value::Null);
                if is_procedure_match_action(input.get("action").and_then(Value::as_str))
                    && memory_call_targets_cwd(input, evaluation_cwd)
                {
                    if let Some(query) = input.get("query").and_then(Value::as_str) {
                        queries.push(query.to_string());
                    }
                    return;
                }
            }
            for child in object.values() {
                collect_claude_procedure_match_queries(child, evaluation_cwd, queries);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_procedure_match_queries(child, evaluation_cwd, queries);
            }
        }
        _ => {}
    }
}

