fn trace_host_identity_read_count(host: &str, path: &Path) -> EvalResult<u32> {
    Ok(trace_host_read_counts(host, path, None)?.0)
}

fn trace_operation_specific_read_count(host: &str, path: &Path, target: &str) -> EvalResult<u32> {
    Ok(trace_host_read_counts(host, path, Some(target))?.1)
}

fn trace_host_read_counts(
    host: &str,
    path: &Path,
    operation_target: Option<&str>,
) -> EvalResult<(u32, u32)> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut identity_reads = 0_u32;
    let mut operation_reads = 0_u32;
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        match host {
            "codex" => {
                if value.get("type").and_then(Value::as_str) != Some("item.completed") {
                    continue;
                }
                let Some(item) = value.get("item").filter(|item| {
                    item.get("type").and_then(Value::as_str) == Some("command_execution")
                }) else {
                    continue;
                };
                let command = item
                    .get("command")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                identity_reads = identity_reads
                    .saturating_add(u32::from(command_reads_checkout_identity(command)));
                operation_reads = operation_reads.saturating_add(u32::from(
                    operation_target.is_some_and(|target| command.contains(target)),
                ));
            }
            "claude_code" => collect_claude_host_read_counts(
                &value,
                operation_target,
                &mut identity_reads,
                &mut operation_reads,
            ),
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in identity-read audit: {other}"
                )))
            }
        }
    }
    Ok((identity_reads, operation_reads))
}

fn collect_claude_host_read_counts(
    value: &Value,
    operation_target: Option<&str>,
    identity_reads: &mut u32,
    operation_reads: &mut u32,
) {
    match value {
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("tool_use") {
                match object.get("name").and_then(Value::as_str) {
                    Some("Bash") => {
                        let command = object
                            .get("input")
                            .and_then(|input| input.get("command"))
                            .and_then(Value::as_str)
                            .unwrap_or_default();
                        *identity_reads = identity_reads
                            .saturating_add(u32::from(command_reads_checkout_identity(command)));
                        *operation_reads = operation_reads.saturating_add(u32::from(
                            operation_target.is_some_and(|target| command.contains(target)),
                        ));
                        return;
                    }
                    Some("Read") => {
                        let read_path = object
                            .get("input")
                            .and_then(|input| input.get("file_path").or_else(|| input.get("path")))
                            .and_then(Value::as_str)
                            .unwrap_or_default();
                        let lower = read_path.to_ascii_lowercase();
                        *identity_reads = identity_reads.saturating_add(u32::from(
                            lower.ends_with("component.json") || lower.ends_with("readme.md"),
                        ));
                        *operation_reads = operation_reads.saturating_add(u32::from(
                            operation_target.is_some_and(|target| read_path.ends_with(target)),
                        ));
                        return;
                    }
                    _ => {}
                }
            }
            for child in object.values() {
                collect_claude_host_read_counts(
                    child,
                    operation_target,
                    identity_reads,
                    operation_reads,
                );
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_host_read_counts(
                    child,
                    operation_target,
                    identity_reads,
                    operation_reads,
                );
            }
        }
        _ => {}
    }
}

fn command_reads_checkout_identity(command: &str) -> bool {
    let lower = command.to_ascii_lowercase();
    lower.contains("git ") || lower.contains("component.json") || lower.contains("readme.md")
}

fn trace_engram_orientation(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
) -> EvalResult<Option<TraceOrientation>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut claude_orient_ids = BTreeSet::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        let text = match host {
            "codex" => codex_orient_result_text(&value, evaluation_cwd),
            "claude_code" => {
                collect_claude_orient_ids(&value, evaluation_cwd, &mut claude_orient_ids);
                claude_orient_result_text(&value, &claude_orient_ids)
            }
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in trusted orientation extraction: {other}"
                )))
            }
        };
        if let Some(text) = text {
            let orientation = serde_json::from_str(&text).map_err(|error| {
                EvalError::Invalid(format!(
                    "trusted Engram orient result at {} line {} is invalid JSON: {error}",
                    path.display(),
                    index + 1
                ))
            })?;
            return Ok(Some(orientation));
        }
    }
    Ok(None)
}

fn codex_orient_result_text(value: &Value, evaluation_cwd: &Path) -> Option<String> {
    let item = value.get("item")?;
    if value.get("type").and_then(Value::as_str) != Some("item.completed")
        || item.get("type").and_then(Value::as_str) != Some("mcp_tool_call")
        || item.get("server").and_then(Value::as_str) != Some("engram")
        || item.get("tool").and_then(Value::as_str) != Some("orient")
        || item.pointer("/arguments/cwd").and_then(Value::as_str)
            != Some(evaluation_cwd.to_string_lossy().as_ref())
        || item.get("error").is_some_and(|error| !error.is_null())
    {
        return None;
    }
    let mut text = String::new();
    collect_text(item.get("result")?, &mut text);
    (!text.is_empty()).then_some(text)
}

fn collect_claude_orient_ids(
    value: &Value,
    evaluation_cwd: &Path,
    orient_ids: &mut BTreeSet<String>,
) {
    match value {
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("tool_use")
                && object.get("name").and_then(Value::as_str) == Some("mcp__engram__orient")
                && object
                    .get("input")
                    .and_then(|input| input.get("cwd"))
                    .and_then(Value::as_str)
                    == Some(evaluation_cwd.to_string_lossy().as_ref())
            {
                if let Some(id) = object.get("id").and_then(Value::as_str) {
                    orient_ids.insert(id.to_string());
                }
                return;
            }
            for child in object.values() {
                collect_claude_orient_ids(child, evaluation_cwd, orient_ids);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_orient_ids(child, evaluation_cwd, orient_ids);
            }
        }
        _ => {}
    }
}

fn claude_orient_result_text(value: &Value, orient_ids: &BTreeSet<String>) -> Option<String> {
    match value {
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("tool_result") {
                let id = object.get("tool_use_id").and_then(Value::as_str)?;
                if !orient_ids.contains(id)
                    || object.get("is_error").and_then(Value::as_bool) == Some(true)
                {
                    return None;
                }
                let mut text = String::new();
                collect_text(object.get("content")?, &mut text);
                return (!text.is_empty()).then_some(text);
            }
            object
                .values()
                .find_map(|child| claude_orient_result_text(child, orient_ids))
        }
        Value::Array(values) => values
            .iter()
            .find_map(|child| claude_orient_result_text(child, orient_ids)),
        _ => None,
    }
}

fn verify_component_evidence(
    evaluation_cwd: &Path,
    evidence: &TraceComponentEvidence,
) -> EvalResult<bool> {
    let component_path = Path::new(&evidence.component_path);
    let (Some(source_path), Some(source_sha256)) = (
        evidence.source_path.as_deref(),
        evidence.source_sha256.as_deref(),
    ) else {
        return Ok(false);
    };
    let source_path = Path::new(source_path);
    if !is_safe_relative_path(component_path)
        || !is_safe_relative_path(source_path)
        || source_path != component_path.join("component.json")
        || source_sha256.len() != 64
        || !source_sha256.bytes().all(|byte| byte.is_ascii_hexdigit())
    {
        return Ok(false);
    }
    let root_output = Command::new("git")
        .args(["-C"])
        .arg(evaluation_cwd)
        .args(["rev-parse", "--show-toplevel"])
        .output()?;
    if !root_output.status.success() {
        return Ok(false);
    }
    let checkout_root = PathBuf::from(String::from_utf8_lossy(&root_output.stdout).trim());
    let component_root = checkout_root.join(component_path);
    let canonical_cwd = match fs::canonicalize(evaluation_cwd) {
        Ok(path) => path,
        Err(_) => return Ok(false),
    };
    let canonical_component_root = match fs::canonicalize(&component_root) {
        Ok(path) => path,
        Err(_) => return Ok(false),
    };
    if !canonical_cwd.starts_with(&canonical_component_root) {
        return Ok(false);
    }
    let manifest = checkout_root.join(source_path);
    let metadata = match fs::symlink_metadata(&manifest) {
        Ok(metadata) => metadata,
        Err(_) => return Ok(false),
    };
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Ok(false);
    }
    let tracked = Command::new("git")
        .arg("-C")
        .arg(&checkout_root)
        .args(["ls-files", "--error-unmatch", "--"])
        .arg(source_path)
        .output()?;
    if !tracked.status.success() {
        return Ok(false);
    }
    Ok(sha256_file(&manifest)? == source_sha256.to_ascii_lowercase())
}

fn is_safe_relative_path(path: &Path) -> bool {
    !path.as_os_str().is_empty()
        && path
            .components()
            .all(|component| matches!(component, std::path::Component::Normal(_)))
}

fn trace_tool_results_contain_normalized_remote(
    host: &str,
    path: &Path,
    expected_remote: &str,
) -> EvalResult<bool> {
    let expected = crate::normalize_remote(expected_remote);
    Ok(trace_tool_result_texts(host, path)?.iter().any(|text| {
        let normalized_text = text
            .to_ascii_lowercase()
            .replace("https://", "")
            .replace("http://", "")
            .replace("ssh://", "")
            .replace("git@", "")
            .replace(':', "/")
            .replace(".git", "");
        normalized_text.contains(&expected)
    }))
}

fn trace_tool_result_texts(host: &str, path: &Path) -> EvalResult<Vec<String>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut texts = Vec::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        match host {
            "codex" => collect_codex_tool_result_texts(&value, &mut texts),
            "claude_code" => collect_claude_tool_result_texts(&value, &mut texts),
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in trusted trace extraction: {other}"
                )))
            }
        }
    }
    Ok(texts)
}

