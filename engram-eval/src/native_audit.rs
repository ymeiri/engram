fn trace_proves_engram_condition_observation_with_expiration(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    expected: &NativePilotConditionObservation,
    expects_expired: bool,
    expected_expiration_title: Option<&str>,
) -> EvalResult<bool> {
    let source_state_matches = match expected.status {
        NativePilotConditionObservationStatus::Matched
        | NativePilotConditionObservationStatus::Mismatched => {
            match (
                expected.source_output_contains.as_deref(),
                expected.source_sha256.as_deref(),
            ) {
                (Some(excerpt), Some(source_sha256)) => condition_source(
                    evaluation_cwd,
                    &expected.source.relative_path,
                    excerpt,
                    source_sha256,
                )?
                .is_some(),
                _ => false,
            }
        }
        NativePilotConditionObservationStatus::Unavailable => {
            missing_condition_source(evaluation_cwd, &expected.source.relative_path)?.is_some()
        }
    };
    if !source_state_matches {
        return Ok(false);
    }
    let reader = BufReader::new(fs::File::open(path)?);
    let mut codex_results = Vec::new();
    let mut claude_use_counts = BTreeMap::<String, u32>::new();
    let mut claude_results = BTreeMap::<String, Vec<ClaudeToolResult>>::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        match host {
            "codex" => {
                if let Some(text) = codex_procedure_match_result_text(&value, evaluation_cwd) {
                    codex_results.push(text);
                }
            }
            "claude_code" => collect_claude_procedure_match_events(
                &value,
                evaluation_cwd,
                &mut claude_use_counts,
                &mut claude_results,
            ),
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in prerequisite-observation audit: {other}"
                )))
            }
        }
    }
    let result = match host {
        "codex" => (codex_results.len() == 1).then(|| codex_results.remove(0)),
        "claude_code" if claude_use_counts.len() == 1 => {
            claude_use_counts.iter().find_map(|(id, count)| {
                (*count == 1)
                    .then(|| claude_results.get(id))
                    .flatten()
                    .filter(|results| results.len() == 1)
                    .and_then(|results| results.first())
                    .filter(|result| result.is_error != Some(true))
                    .map(|result| result.content.clone())
            })
        }
        "claude_code" => None,
        _ => unreachable!(),
    };
    Ok(result.as_deref().is_some_and(|text| {
        condition_observation_result_matches_with_expiration(
            text,
            expected,
            expects_expired,
            expected_expiration_title,
        )
    }))
}

fn codex_procedure_match_result_text(value: &Value, evaluation_cwd: &Path) -> Option<String> {
    let item = value.get("item")?;
    let arguments = item.get("arguments")?;
    if value.get("type").and_then(Value::as_str) != Some("item.completed")
        || item.get("type").and_then(Value::as_str) != Some("mcp_tool_call")
        || item.get("server").and_then(Value::as_str) != Some("engram")
        || item.get("tool").and_then(Value::as_str) != Some("memory")
        || !is_procedure_match_action(arguments.get("action").and_then(Value::as_str))
        || !memory_call_targets_cwd(arguments, evaluation_cwd)
        || item.get("error").is_some_and(|error| !error.is_null())
    {
        return None;
    }
    let mut text = String::new();
    collect_text(item.get("result")?, &mut text);
    (!text.is_empty()).then_some(text)
}

fn collect_claude_procedure_match_events(
    value: &Value,
    evaluation_cwd: &Path,
    use_counts: &mut BTreeMap<String, u32>,
    results: &mut BTreeMap<String, Vec<ClaudeToolResult>>,
) {
    match value {
        Value::Object(object) => {
            match object.get("type").and_then(Value::as_str) {
                Some("tool_use")
                    if object.get("name").and_then(Value::as_str)
                        == Some("mcp__engram__memory")
                        && object.get("input").is_some_and(|input| {
                            is_procedure_match_action(input.get("action").and_then(Value::as_str))
                        })
                        && object.get("input").is_some_and(|input| {
                            memory_call_targets_cwd(input, evaluation_cwd)
                        }) =>
                {
                    if let Some(id) = object.get("id").and_then(Value::as_str) {
                        *use_counts.entry(id.to_string()).or_default() += 1;
                    }
                    return;
                }
                Some("tool_result") => {
                    if let Some(id) = object.get("tool_use_id").and_then(Value::as_str) {
                        let mut content = String::new();
                        if let Some(value) = object.get("content") {
                            collect_text(value, &mut content);
                        }
                        results
                            .entry(id.to_string())
                            .or_default()
                            .push(ClaudeToolResult {
                                is_error: object.get("is_error").and_then(Value::as_bool),
                                content,
                            });
                    }
                    return;
                }
                _ => {}
            }
            for child in object.values() {
                collect_claude_procedure_match_events(child, evaluation_cwd, use_counts, results);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_procedure_match_events(child, evaluation_cwd, use_counts, results);
            }
        }
        _ => {}
    }
}

fn memory_call_targets_cwd(arguments: &Value, evaluation_cwd: &Path) -> bool {
    let expected = evaluation_cwd.to_string_lossy();
    let top_level = match arguments.get("cwd") {
        None | Some(Value::Null) => None,
        Some(Value::String(cwd)) => Some(cwd.as_str()),
        Some(_) => return false,
    };
    let scope = arguments.get("scope");
    let search_scope = arguments.get("search_scope");
    if scope.is_some() && search_scope.is_some() {
        return false;
    }
    let nested = match scope.or(search_scope) {
        None | Some(Value::Null) => None,
        Some(Value::Object(scope)) => match scope.get("cwd") {
            None | Some(Value::Null) => None,
            Some(Value::String(cwd)) => Some(cwd.as_str()),
            Some(_) => return false,
        },
        Some(_) => return false,
    };
    if top_level
        .zip(nested)
        .is_some_and(|(top_level, nested)| top_level != nested)
    {
        return false;
    }
    nested.or(top_level) == Some(expected.as_ref())
}

fn is_procedure_match_action(action: Option<&str>) -> bool {
    action.is_some_and(|action| {
        matches!(
            action.to_lowercase().as_str(),
            "procedure_match" | "procedure-match"
        )
    })
}

fn memory_action_matches(actual: &str, expected: &str) -> bool {
    if is_procedure_match_action(Some(expected)) {
        is_procedure_match_action(Some(actual))
    } else {
        actual == expected
    }
}

#[cfg(test)]
fn condition_observation_result_matches(
    text: &str,
    expected: &NativePilotConditionObservation,
) -> bool {
    condition_observation_result_matches_with_expiration(text, expected, false, None)
}

fn condition_observation_result_matches_with_expiration(
    text: &str,
    expected: &NativePilotConditionObservation,
    expects_expired: bool,
    expected_expiration_title: Option<&str>,
) -> bool {
    let Ok(report) = serde_json::from_str::<Value>(text) else {
        return false;
    };
    let expected_status = serde_json::to_value(expected.status)
        .ok()
        .and_then(|value| value.as_str().map(str::to_string));
    let expected_status = expected_status.as_deref();
    let observation_matches = |diagnostic: &Value| {
        diagnostic
            .get("condition_observations")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .any(|observation| {
                let Some(object) = observation.as_object() else {
                    return false;
                };
                let Some(source) = observation.get("source").and_then(Value::as_object) else {
                    return false;
                };
                object.len() == 5
                    && source.len() == 3
                    && observation.get("condition_key").and_then(Value::as_str)
                        == Some(expected.condition_key.as_str())
                    && observation.get("status").and_then(Value::as_str) == expected_status
                    && match expected.source_sha256.as_deref() {
                        Some(expected_sha256) => {
                            observation.get("source_sha256").and_then(Value::as_str)
                                == Some(expected_sha256)
                        }
                        None => observation.get("source_sha256").is_some_and(Value::is_null),
                    }
                    && source.get("format").and_then(Value::as_str)
                        == Some(expected.source.format.as_str())
                    && source.get("relative_path").and_then(Value::as_str)
                        == Some(expected.source.relative_path.as_str())
                    && source.get("key_path") == Some(&serde_json::json!(expected.source.key_path))
                    && observation
                        .get("detail")
                        .and_then(Value::as_str)
                        .is_some_and(|detail| match expected.detail_contains.as_deref() {
                            Some(expected_detail) => detail.contains(expected_detail),
                            None => true,
                        })
            })
    };
    let outcome_matches = if expects_expired {
        report.get("abstained").and_then(Value::as_bool) == Some(true)
    } else {
        match expected.status {
            NativePilotConditionObservationStatus::Matched => {
                report.get("abstained").and_then(Value::as_bool) == Some(false)
            }
            NativePilotConditionObservationStatus::Mismatched => {
                report.get("abstained").and_then(Value::as_bool) == Some(true)
            }
            NativePilotConditionObservationStatus::Unavailable => {
                report.get("abstained").and_then(Value::as_bool) == Some(true)
            }
        }
    };
    let expiration_matches = !expects_expired
        || report
            .get("procedures")
            .and_then(Value::as_array)
            .is_some_and(Vec::is_empty)
            && report
                .get("diagnostics")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
                .any(|diagnostic| {
                    expected_expiration_title.is_some_and(|title| {
                        diagnostic.get("title").and_then(Value::as_str) == Some(title)
                    }) && diagnostic.get("applicable").and_then(Value::as_bool) == Some(false)
                        && diagnostic
                            .get("reasons")
                            .and_then(Value::as_array)
                            .into_iter()
                            .flatten()
                            .any(|reason| {
                                reason.as_str() == Some("Procedure verification has expired.")
                            })
                        && observation_matches(diagnostic)
                });
    outcome_matches
        && expiration_matches
        && report
            .get("diagnostics")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .any(observation_matches)
}

fn trace_proves_condition_evidence(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    target: &str,
    excerpt: &str,
    source_sha256: &str,
) -> EvalResult<bool> {
    trace_proves_checkout_evidence(host, path, evaluation_cwd, target, excerpt, source_sha256)
}

fn trace_proves_optional_identity_evidence(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    expected: Option<&str>,
    target: Option<&str>,
    excerpt: Option<&str>,
    source_sha256: Option<&str>,
) -> EvalResult<bool> {
    let Some(expected) = expected else {
        return Ok(target.is_none() && excerpt.is_none() && source_sha256.is_none());
    };
    let (Some(target), Some(excerpt), Some(source_sha256)) = (target, excerpt, source_sha256)
    else {
        return Ok(false);
    };
    if !excerpt
        .to_ascii_lowercase()
        .contains(&expected.to_ascii_lowercase())
    {
        return Ok(false);
    }
    trace_proves_checkout_evidence(host, path, evaluation_cwd, target, excerpt, source_sha256)
}

fn trace_proves_checkout_evidence(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    target: &str,
    excerpt: &str,
    source_sha256: &str,
) -> EvalResult<bool> {
    let Some(source) = condition_source(evaluation_cwd, target, excerpt, source_sha256)? else {
        return Ok(false);
    };
    if host == "claude_code" {
        return claude_trace_proves_condition_evidence(path, evaluation_cwd, &source, excerpt);
    }
    if host != "codex" {
        return Err(EvalError::Invalid(format!(
            "unsupported host in condition-evidence audit: {host}"
        )));
    }
    let reader = BufReader::new(fs::File::open(path)?);
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "evaluation trace line {} is invalid JSON: {error}",
                index + 1
            ))
        })?;
        let Some(item) = value
            .get("item")
            .filter(|item| item.get("type").and_then(Value::as_str) == Some("command_execution"))
        else {
            continue;
        };
        let command = item
            .get("command")
            .and_then(Value::as_str)
            .unwrap_or_default();
        let output = item
            .get("aggregated_output")
            .and_then(Value::as_str)
            .unwrap_or_default();
        if condition_inspection_command(command, evaluation_cwd, &source)
            && item.get("status").and_then(Value::as_str) == Some("completed")
            && item.get("exit_code").and_then(Value::as_i64) == Some(0)
            && output.contains(excerpt)
        {
            return Ok(true);
        }
    }
    Ok(false)
}

pub(crate) fn trace_proves_missing_checkout_evidence(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    target: &str,
) -> EvalResult<bool> {
    let Some(source) = missing_condition_source(evaluation_cwd, target)? else {
        return Ok(false);
    };
    let reader = BufReader::new(fs::File::open(path)?);
    let mut claude_uses = Vec::new();
    let mut claude_results = BTreeMap::<String, Vec<ClaudeToolResult>>::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "evaluation trace line {} is invalid JSON: {error}",
                index + 1
            ))
        })?;
        match host {
            "codex" => {
                let Some(item) = value.get("item").filter(|item| {
                    item.get("type").and_then(Value::as_str) == Some("command_execution")
                }) else {
                    continue;
                };
                let command = item
                    .get("command")
                    .and_then(Value::as_str)
                    .unwrap_or_default();
                if missing_condition_inspection_command(command, evaluation_cwd, &source)
                    && item.get("status").and_then(Value::as_str) == Some("completed")
                    && item
                        .get("exit_code")
                        .and_then(Value::as_i64)
                        .is_some_and(|exit| exit != 0)
                {
                    return Ok(true);
                }
            }
            "claude_code" => collect_claude_missing_condition_events(
                &value,
                evaluation_cwd,
                &source,
                &mut claude_uses,
                &mut claude_results,
            ),
            other => {
                return Err(EvalError::Invalid(format!(
                    "unsupported host in missing-condition audit: {other}"
                )))
            }
        }
    }
    if host != "claude_code" {
        return Ok(false);
    }
    let mut use_counts = BTreeMap::new();
    for id in &claude_uses {
        *use_counts.entry(id.clone()).or_insert(0_u32) += 1;
    }
    Ok(claude_uses.into_iter().any(|id| {
        use_counts.get(&id) == Some(&1)
            && claude_results
                .get(id.as_str())
                .filter(|values| values.len() == 1)
                .and_then(|values| values.first())
                .is_some_and(|result| result.is_error == Some(true))
    }))
}

fn collect_claude_missing_condition_events(
    value: &Value,
    evaluation_cwd: &Path,
    source: &Path,
    uses: &mut Vec<String>,
    results: &mut BTreeMap<String, Vec<ClaudeToolResult>>,
) {
    match value {
        Value::Object(object) => {
            match object.get("type").and_then(Value::as_str) {
                Some("tool_use") => {
                    let name = object.get("name").and_then(Value::as_str);
                    let input = object.get("input");
                    let inspectable = match name {
                        Some("Read") => input
                            .and_then(|input| input.get("file_path").or_else(|| input.get("path")))
                            .and_then(Value::as_str)
                            .is_some_and(|path| {
                                missing_path_argument_matches(path, evaluation_cwd, source)
                            }),
                        Some("Bash") => input
                            .and_then(|input| input.get("command"))
                            .and_then(Value::as_str)
                            .is_some_and(|command| {
                                missing_condition_inspection_command(
                                    command,
                                    evaluation_cwd,
                                    source,
                                )
                            }),
                        _ => false,
                    };
                    if inspectable {
                        if let Some(id) = object.get("id").and_then(Value::as_str) {
                            uses.push(id.to_string());
                        }
                    }
                    return;
                }
                Some("tool_result") => {
                    if let Some(id) = object.get("tool_use_id").and_then(Value::as_str) {
                        let mut content = String::new();
                        if let Some(value) = object.get("content") {
                            collect_text(value, &mut content);
                        }
                        results
                            .entry(id.to_string())
                            .or_default()
                            .push(ClaudeToolResult {
                                is_error: object.get("is_error").and_then(Value::as_bool),
                                content,
                            });
                    }
                    return;
                }
                _ => {}
            }
            for child in object.values() {
                collect_claude_missing_condition_events(
                    child,
                    evaluation_cwd,
                    source,
                    uses,
                    results,
                );
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_missing_condition_events(
                    child,
                    evaluation_cwd,
                    source,
                    uses,
                    results,
                );
            }
        }
        _ => {}
    }
}

fn condition_source(
    evaluation_cwd: &Path,
    target: &str,
    excerpt: &str,
    expected_sha256: &str,
) -> EvalResult<Option<PathBuf>> {
    let target = Path::new(target);
    if !is_safe_relative_path(target) {
        return Ok(None);
    }
    let output = Command::new("git")
        .arg("-C")
        .arg(evaluation_cwd)
        .args(["rev-parse", "--show-toplevel"])
        .output()?;
    if !output.status.success() {
        return Ok(None);
    }
    let checkout = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim()).canonicalize()?;
    let source = checkout.join(target);
    let metadata = match fs::symlink_metadata(&source) {
        Ok(metadata) => metadata,
        Err(_) => return Ok(None),
    };
    if metadata.file_type().is_symlink() || !metadata.is_file() {
        return Ok(None);
    }
    let source = source.canonicalize()?;
    if !source.starts_with(&checkout) {
        return Ok(None);
    }
    let tracked = Command::new("git")
        .arg("-C")
        .arg(&checkout)
        .args(["ls-files", "--error-unmatch", "--"])
        .arg(target)
        .output()?;
    if !tracked.status.success()
        || sha256_file(&source)? != expected_sha256.to_ascii_lowercase()
        || !fs::read_to_string(&source)?.contains(excerpt)
    {
        return Ok(None);
    }
    Ok(Some(source))
}

fn missing_condition_source(evaluation_cwd: &Path, target: &str) -> EvalResult<Option<PathBuf>> {
    let target = Path::new(target);
    if !is_safe_relative_path(target) {
        return Ok(None);
    }
    let output = Command::new("git")
        .arg("-C")
        .arg(evaluation_cwd)
        .args(["rev-parse", "--show-toplevel"])
        .output()?;
    if !output.status.success() {
        return Ok(None);
    }
    let checkout = PathBuf::from(String::from_utf8_lossy(&output.stdout).trim()).canonicalize()?;
    let tracked = Command::new("git")
        .arg("-C")
        .arg(&checkout)
        .args(["--literal-pathspecs", "ls-files", "--error-unmatch", "--"])
        .arg(target)
        .output()?;
    if !tracked.status.success() {
        return Ok(None);
    }
    let source = checkout.join(target);
    if fs::symlink_metadata(&source).is_ok() {
        return Ok(None);
    }
    Ok(Some(source))
}

fn missing_condition_inspection_command(
    command: &str,
    evaluation_cwd: &Path,
    source: &Path,
) -> bool {
    let mut body = command.trim();
    for prefix in ["/bin/zsh -lc ", "/bin/bash -lc ", "zsh -lc ", "bash -lc "] {
        if let Some(inner) = body.strip_prefix(prefix) {
            body = inner.trim();
            if body.len() >= 2 {
                let first = body.as_bytes()[0];
                let last = body.as_bytes()[body.len() - 1];
                if (first == b'\'' && last == b'\'') || (first == b'"' && last == b'"') {
                    body = &body[1..body.len() - 1];
                }
            }
            break;
        }
    }
    if ["#", ";", "&&", "||", "|", ">", "<", "`", "$(", "\n", "\r"]
        .iter()
        .any(|forbidden| body.contains(forbidden))
    {
        return false;
    }
    let mut words = body.split_whitespace();
    let Some(program) = words.next() else {
        return false;
    };
    let program = Path::new(program.trim_matches(['\'', '"']))
        .file_name()
        .and_then(|name| name.to_str());
    if !matches!(
        program,
        Some("cat" | "sed" | "grep" | "rg" | "head" | "tail" | "awk")
    ) {
        return false;
    }
    words.any(|word| missing_path_argument_matches(word, evaluation_cwd, source))
}

fn missing_path_argument_matches(argument: &str, evaluation_cwd: &Path, source: &Path) -> bool {
    let argument = argument.trim_matches(['\'', '"']);
    if argument.is_empty() || argument.starts_with('-') {
        return false;
    }
    let path = Path::new(argument);
    let candidate = if path.is_absolute() {
        path.to_path_buf()
    } else {
        evaluation_cwd.join(path)
    };
    let Some(parent) = candidate.parent() else {
        return false;
    };
    let Some(file_name) = candidate.file_name() else {
        return false;
    };
    parent
        .canonicalize()
        .ok()
        .map(|parent| parent.join(file_name))
        .as_deref()
        == Some(source)
}

fn condition_inspection_command(command: &str, evaluation_cwd: &Path, source: &Path) -> bool {
    let mut body = command.trim();
    for prefix in ["/bin/zsh -lc ", "/bin/bash -lc ", "zsh -lc ", "bash -lc "] {
        if let Some(inner) = body.strip_prefix(prefix) {
            body = inner.trim();
            if body.len() >= 2 {
                let first = body.as_bytes()[0];
                let last = body.as_bytes()[body.len() - 1];
                if (first == b'\'' && last == b'\'') || (first == b'"' && last == b'"') {
                    body = &body[1..body.len() - 1];
                }
            }
            break;
        }
    }
    if ["#", ";", "&&", "||", "|", ">", "<", "`", "$(", "\n", "\r"]
        .iter()
        .any(|forbidden| body.contains(forbidden))
    {
        return false;
    }
    let mut words = body.split_whitespace();
    let Some(program) = words.next() else {
        return false;
    };
    let program = Path::new(program.trim_matches(['\'', '"']))
        .file_name()
        .and_then(|name| name.to_str());
    if !matches!(
        program,
        Some("cat" | "sed" | "grep" | "rg" | "head" | "tail" | "awk")
    ) {
        return false;
    }
    words.any(|word| {
        let argument = word
            .strip_prefix("\\\"")
            .and_then(|inner| inner.strip_suffix("\\\""))
            .unwrap_or_else(|| word.trim_matches(['\'', '"']));
        let path = Path::new(argument);
        if argument.is_empty() || argument.starts_with('-') {
            return false;
        }
        let candidate = if path.is_absolute() {
            path.to_path_buf()
        } else {
            evaluation_cwd.join(path)
        };
        candidate.canonicalize().ok().as_deref() == Some(source)
    })
}

fn claude_trace_proves_condition_evidence(
    path: &Path,
    evaluation_cwd: &Path,
    source: &Path,
    excerpt: &str,
) -> EvalResult<bool> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut uses = Vec::new();
    let mut results: BTreeMap<String, Vec<ClaudeToolResult>> = BTreeMap::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid Claude JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        collect_claude_condition_events(&value, evaluation_cwd, source, &mut uses, &mut results);
    }
    let mut use_counts = BTreeMap::new();
    for id in &uses {
        *use_counts.entry(id.clone()).or_insert(0_u32) += 1;
    }
    Ok(uses.into_iter().any(|id| {
        use_counts.get(&id) == Some(&1)
            && results
                .get(id.as_str())
                .filter(|values| values.len() == 1)
                .and_then(|values| values.first())
                .is_some_and(|result| {
                    result.is_error != Some(true) && result.content.contains(excerpt)
                })
    }))
}

fn collect_claude_condition_events(
    value: &Value,
    evaluation_cwd: &Path,
    source: &Path,
    uses: &mut Vec<String>,
    results: &mut BTreeMap<String, Vec<ClaudeToolResult>>,
) {
    match value {
        Value::Object(object) => {
            match object.get("type").and_then(Value::as_str) {
                Some("tool_use") => {
                    let name = object.get("name").and_then(Value::as_str);
                    let input = object.get("input");
                    let inspectable = match name {
                        Some("Read") => input
                            .and_then(|input| input.get("file_path").or_else(|| input.get("path")))
                            .and_then(Value::as_str)
                            .is_some_and(|path| {
                                let path = Path::new(path);
                                let candidate = if path.is_absolute() {
                                    path.to_path_buf()
                                } else {
                                    evaluation_cwd.join(path)
                                };
                                candidate.canonicalize().ok().as_deref() == Some(source)
                            }),
                        Some("Bash") => input
                            .and_then(|input| input.get("command"))
                            .and_then(Value::as_str)
                            .is_some_and(|command| {
                                condition_inspection_command(command, evaluation_cwd, source)
                            }),
                        _ => false,
                    };
                    if inspectable {
                        if let Some(id) = object.get("id").and_then(Value::as_str) {
                            uses.push(id.to_string());
                        }
                    }
                    return;
                }
                Some("tool_result") => {
                    if let Some(id) = object.get("tool_use_id").and_then(Value::as_str) {
                        let mut content = String::new();
                        if let Some(value) = object.get("content") {
                            collect_text(value, &mut content);
                        }
                        results
                            .entry(id.to_string())
                            .or_default()
                            .push(ClaudeToolResult {
                                is_error: object.get("is_error").and_then(Value::as_bool),
                                content,
                            });
                    }
                    return;
                }
                _ => {}
            }
            for child in object.values() {
                collect_claude_condition_events(child, evaluation_cwd, source, uses, results);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_condition_events(child, evaluation_cwd, source, uses, results);
            }
        }
        _ => {}
    }
}

fn value_has_memory_action(value: &Value, expected: &str) -> bool {
    match value {
        Value::Object(object) => {
            let identifies_memory_tool = ["name", "tool", "tool_name"].iter().any(|key| {
                object
                    .get(*key)
                    .and_then(Value::as_str)
                    .is_some_and(|name| name.to_ascii_lowercase().contains("memory"))
            });
            let contains_action = object
                .get("action")
                .and_then(Value::as_str)
                .is_some_and(|action| memory_action_matches(action, expected))
                || object
                    .values()
                    .any(|value| value_contains_action(value, expected));
            if identifies_memory_tool && contains_action {
                return true;
            }
            object
                .values()
                .any(|value| value_has_memory_action(value, expected))
        }
        Value::Array(values) => values
            .iter()
            .any(|value| value_has_memory_action(value, expected)),
        Value::String(value) => serde_json::from_str::<Value>(value)
            .ok()
            .is_some_and(|value| value_has_memory_action(&value, expected)),
        _ => false,
    }
}

fn value_contains_action(value: &Value, expected: &str) -> bool {
    match value {
        Value::Object(object) => {
            object
                .get("action")
                .and_then(Value::as_str)
                .is_some_and(|action| memory_action_matches(action, expected))
                || object
                    .values()
                    .any(|value| value_contains_action(value, expected))
        }
        Value::Array(values) => values
            .iter()
            .any(|value| value_contains_action(value, expected)),
        Value::String(value) => serde_json::from_str::<Value>(value)
            .ok()
            .is_some_and(|value| value_contains_action(&value, expected)),
        _ => false,
    }
}

fn find_native_memory_writes(
    trace_path: &Path,
    gates: &[NativeArtifactGate],
) -> EvalResult<Vec<String>> {
    let commands = shell_commands_from_jsonl(trace_path)?;
    let native_paths = gates
        .iter()
        .filter(|gate| gate.layer.contains("native_memory") || gate.layer.contains("auto_memory"))
        .map(|gate| gate.path.to_lowercase())
        .collect::<Vec<_>>();
    let mut findings = Vec::new();
    for command in commands {
        let lower = command.to_lowercase();
        let names_memory = lower.contains("codex_home")
            || lower.contains("claude_config_dir")
            || lower.contains("memory.md")
            || lower.contains("/memories")
            || native_paths.iter().any(|path| lower.contains(path));
        let writes = [
            ">",
            "tee ",
            "cp ",
            "mv ",
            "touch ",
            "mkdir ",
            "install ",
            "sed -i",
            "write_text",
            "write_bytes",
            "open(",
            "fs.write",
            "file::create",
        ]
        .iter()
        .any(|token| lower.contains(token));
        if names_memory && writes {
            findings.push(command);
        }
    }
    Ok(findings)
}

fn audit_jsonl(path: &Path, label: &str) -> EvalResult<FileAudit> {
    if !path.exists() {
        return Ok(pending_file(
            path,
            &format!("{label} has not been captured"),
        ));
    }
    let metadata = fs::metadata(path)?;
    if !metadata.is_file() || metadata.len() == 0 {
        return Ok(failed_file(
            path,
            &format!("{label} is not a non-empty file"),
        ));
    }
    if metadata.len() > MAX_TRACE_BYTES {
        return Ok(failed_file(
            path,
            &format!("{label} exceeds the {} byte audit limit", MAX_TRACE_BYTES),
        ));
    }
    let body = fs::read_to_string(path)?;
    let lines = body
        .lines()
        .filter(|line| !line.trim().is_empty())
        .collect::<Vec<_>>();
    if lines.is_empty() {
        return Ok(failed_file(
            path,
            &format!("{label} contains no JSON events"),
        ));
    }
    if lines
        .iter()
        .any(|line| serde_json::from_str::<Value>(line).is_err())
    {
        return Ok(failed_file(path, &format!("{label} is not valid JSONL")));
    }
    passed_file(path, format!("{label} is valid non-empty JSONL"))
}

fn audit_json(path: &Path, label: &str) -> EvalResult<FileAudit> {
    if !path.exists() {
        return Ok(pending_file(
            path,
            &format!("{label} has not been captured"),
        ));
    }
    let metadata = fs::metadata(path)?;
    if !metadata.is_file() || metadata.len() == 0 {
        return Ok(failed_file(
            path,
            &format!("{label} is not a non-empty file"),
        ));
    }
    if serde_json::from_reader::<_, Value>(fs::File::open(path)?).is_err() {
        return Ok(failed_file(path, &format!("{label} is not valid JSON")));
    }
    passed_file(path, format!("{label} is valid non-empty JSON"))
}

fn pending_file(path: &Path, detail: &str) -> FileAudit {
    FileAudit {
        status: AuditStatus::Pending,
        path: path.display().to_string(),
        sha256: None,
        modified_unix_ms: None,
        detail: detail.to_string(),
    }
}

fn failed_file(path: &Path, detail: &str) -> FileAudit {
    FileAudit {
        status: AuditStatus::Failed,
        path: path.display().to_string(),
        sha256: None,
        modified_unix_ms: modified_unix_ms(path).ok(),
        detail: detail.to_string(),
    }
}

fn passed_file(path: &Path, detail: String) -> EvalResult<FileAudit> {
    Ok(FileAudit {
        status: AuditStatus::Passed,
        path: path.display().to_string(),
        sha256: Some(sha256_file(path)?),
        modified_unix_ms: Some(modified_unix_ms(path)?),
        detail,
    })
}

fn collect_failure(audit: &FileAudit, failures: &mut Vec<String>) {
    if audit.status == AuditStatus::Failed {
        failures.push(audit.detail.clone());
    }
}

#[derive(Debug, Default, PartialEq, Eq)]
struct HostCommandEvidence {
    relevant_attempts: u32,
    first_procedure_attempt_correct: bool,
    successful_command_executed: bool,
    expected_exit_observed: bool,
    success_marker_observed: bool,
    repeated_failures: u32,
}

#[derive(Debug)]
struct HostCommandAttempt {
    command: String,
    expected_exit_observed: bool,
    captured_exit_observed: bool,
    success_marker_observed: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum RequiredCommandMatch {
    None,
    ProcessExit,
    CapturedInnerExit,
}

impl RequiredCommandMatch {
    fn matched(self) -> bool {
        self != Self::None
    }

    fn expected_exit_observed(self, attempt: &HostCommandAttempt) -> bool {
        match self {
            Self::None => false,
            Self::ProcessExit => attempt.expected_exit_observed,
            Self::CapturedInnerExit => attempt.captured_exit_observed,
        }
    }
}

#[cfg(test)]
fn host_command_evidence(
    host: &str,
    path: &Path,
    contract: &AcceptanceContract,
) -> EvalResult<HostCommandEvidence> {
    host_command_evidence_with_semantics(host, path, contract, Path::new(""), 4)
}

fn host_command_evidence_with_semantics(
    host: &str,
    path: &Path,
    contract: &AcceptanceContract,
    evaluation_cwd: &Path,
    protocol_schema_version: u32,
) -> EvalResult<HostCommandEvidence> {
    let attempts = match host {
        "codex" => codex_command_attempts(path, contract)?,
        "claude_code" => claude_command_attempts(path, contract)?,
        other => {
            return Err(EvalError::Invalid(format!(
                "unsupported host in native-memory acceptance audit: {other}"
            )))
        }
    };
    let checkout_root = if protocol_schema_version >= 5 {
        repository_root(evaluation_cwd)
    } else {
        None
    };
    let first_relevant = attempts.iter().find(|attempt| {
        required_command_match(
            &attempt.command,
            &contract.required_command,
            checkout_root.as_deref(),
            protocol_schema_version,
        )
        .matched()
            || command_matches_forbidden(&attempt.command, &contract.forbidden_commands)
    });
    let relevant_attempts = attempts
        .iter()
        .filter(|attempt| {
            required_command_match(
                &attempt.command,
                &contract.required_command,
                checkout_root.as_deref(),
                protocol_schema_version,
            )
            .matched()
                || command_matches_forbidden(&attempt.command, &contract.forbidden_commands)
        })
        .count() as u32;
    let first_procedure_attempt_correct = first_relevant.is_some_and(|attempt| {
        required_command_match(
            &attempt.command,
            &contract.required_command,
            checkout_root.as_deref(),
            protocol_schema_version,
        )
        .matched()
            && !command_matches_forbidden(&attempt.command, &contract.forbidden_commands)
    });
    let successful_command_executed = attempts.iter().any(|attempt| {
        let required_match = required_command_match(
            &attempt.command,
            &contract.required_command,
            checkout_root.as_deref(),
            protocol_schema_version,
        );
        required_match.matched()
            && required_match.expected_exit_observed(attempt)
            && attempt.success_marker_observed
    });
    let expected_exit_observed = attempts.iter().any(|attempt| {
        let required_match = required_command_match(
            &attempt.command,
            &contract.required_command,
            checkout_root.as_deref(),
            protocol_schema_version,
        );
        required_match.matched() && required_match.expected_exit_observed(attempt)
    });
    let success_marker_observed = attempts.iter().any(|attempt| {
        required_command_match(
            &attempt.command,
            &contract.required_command,
            checkout_root.as_deref(),
            protocol_schema_version,
        )
        .matched()
            && attempt.success_marker_observed
    });
    let repeated_failures = attempts
        .iter()
        .filter(|attempt| command_matches_forbidden(&attempt.command, &contract.forbidden_commands))
        .count() as u32;
    Ok(HostCommandEvidence {
        relevant_attempts,
        first_procedure_attempt_correct,
        successful_command_executed,
        expected_exit_observed,
        success_marker_observed,
        repeated_failures,
    })
}

pub(crate) fn validate_teaching_command_evidence(
    lane: &PreparedNativeLane,
    protocol_schema_version: u32,
) -> EvalResult<()> {
    let contract: AcceptanceContract =
        serde_json::from_reader(fs::File::open(&lane.acceptance_contract)?)?;
    let evidence = host_command_evidence_with_semantics(
        &lane.host,
        Path::new(&lane.teaching_trace_path),
        &contract,
        Path::new(&lane.teaching_cwd),
        protocol_schema_version,
    )?;
    if !evidence.successful_command_executed {
        return Err(EvalError::Invalid(format!(
            "teaching trace for lane {} did not prove the required command, exit status, and output marker",
            lane.order
        )));
    }
    if !contract.forbidden_commands.is_empty() && evidence.repeated_failures == 0 {
        return Err(EvalError::Invalid(format!(
            "teaching trace for lane {} did not observe the frozen failure signature",
            lane.order
        )));
    }
    Ok(())
}

fn required_command_match(
    command: &str,
    required: &str,
    checkout_root: Option<&Path>,
    protocol_schema_version: u32,
) -> RequiredCommandMatch {
    if protocol_schema_version < 5 {
        return if command.trim() == required.trim() {
            RequiredCommandMatch::ProcessExit
        } else {
            RequiredCommandMatch::None
        };
    }
    let payload = shell_payload(command);
    if command_payload_matches_required(payload, required, checkout_root) {
        return RequiredCommandMatch::ProcessExit;
    }
    if protocol_schema_version >= OPERATION_EVIDENCE_ROUTE_NATIVE_PILOT_SCHEMA_VERSION {
        if let Some(inner) = payload.strip_suffix("; echo \"Exit code: $?\"") {
            if command_payload_matches_required(inner.trim_end(), required, checkout_root) {
                return RequiredCommandMatch::CapturedInnerExit;
            }
        }
    }
    RequiredCommandMatch::None
}

fn command_payload_matches_required(
    payload: &str,
    required: &str,
    checkout_root: Option<&Path>,
) -> bool {
    if payload == required.trim() {
        return true;
    }
    let Some(checkout_root) = checkout_root else {
        return false;
    };
    let root = checkout_root.display().to_string();
    [
        format!("cd {root} && {}", required.trim()),
        format!("cd '{root}' && {}", required.trim()),
        format!("cd \"{root}\" && {}", required.trim()),
    ]
    .iter()
    .any(|candidate| payload == candidate)
}

fn output_reports_exit(output: &str, expected_exit_code: i32) -> bool {
    let expected = format!("Exit code: {expected_exit_code}");
    output.lines().any(|line| line.trim() == expected)
}

fn shell_payload(command: &str) -> &str {
    let command = command.trim();
    let payload = [
        "/bin/zsh -lc ",
        "/bin/bash -lc ",
        "/bin/sh -lc ",
        "zsh -lc ",
        "bash -lc ",
        "sh -lc ",
    ]
    .iter()
    .find_map(|prefix| command.strip_prefix(prefix))
    .unwrap_or(command)
    .trim();
    if payload.len() >= 2 {
        let bytes = payload.as_bytes();
        if (bytes[0] == b'\'' && bytes[payload.len() - 1] == b'\'')
            || (bytes[0] == b'"' && bytes[payload.len() - 1] == b'"')
        {
            return payload[1..payload.len() - 1].trim();
        }
    }
    payload
}

fn repository_root(cwd: &Path) -> Option<PathBuf> {
    let mut current = if cwd.is_dir() {
        cwd.to_path_buf()
    } else {
        cwd.parent()?.to_path_buf()
    };
    loop {
        if current.join(".git").exists() {
            return Some(current);
        }
        if !current.pop() {
            return None;
        }
    }
}

fn live_repository_remote_matches(cwd: &Path, expected_remote: &str) -> EvalResult<bool> {
    let output = Command::new("git")
        .arg("-C")
        .arg(cwd)
        .args(["config", "--get", "remote.origin.url"])
        .output()?;
    if !output.status.success() {
        return Ok(false);
    }
    let observed = String::from_utf8_lossy(&output.stdout);
    Ok(crate::normalize_remote(observed.trim()) == crate::normalize_remote(expected_remote))
}

fn command_matches_forbidden(command: &str, forbidden: &[String]) -> bool {
    forbidden.iter().any(|value| command.contains(value))
}

fn codex_command_attempts(
    path: &Path,
    contract: &AcceptanceContract,
) -> EvalResult<Vec<HostCommandAttempt>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut attempts = Vec::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid Codex JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        if value.get("type").and_then(Value::as_str) != Some("item.completed")
            || value.pointer("/item/type").and_then(Value::as_str) != Some("command_execution")
        {
            continue;
        }
        let Some(command) = value.pointer("/item/command").and_then(Value::as_str) else {
            continue;
        };
        let completed = value.pointer("/item/status").and_then(Value::as_str) == Some("completed");
        let exit_code = value.pointer("/item/exit_code").and_then(Value::as_i64);
        let output = value
            .pointer("/item/aggregated_output")
            .and_then(Value::as_str)
            .unwrap_or_default();
        attempts.push(HostCommandAttempt {
            command: command.to_string(),
            expected_exit_observed: completed
                && exit_code == Some(i64::from(contract.expected_exit_code)),
            captured_exit_observed: output_reports_exit(output, contract.expected_exit_code),
            success_marker_observed: output.contains(&contract.expected_output_contains),
        });
    }
    Ok(attempts)
}

#[derive(Debug)]
struct ClaudeToolUse {
    id: String,
    command: String,
}

#[derive(Debug)]
struct ClaudeToolResult {
    is_error: Option<bool>,
    content: String,
}

fn claude_command_attempts(
    path: &Path,
    contract: &AcceptanceContract,
) -> EvalResult<Vec<HostCommandAttempt>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut uses = Vec::new();
    let mut results: BTreeMap<String, Vec<ClaudeToolResult>> = BTreeMap::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid Claude JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        collect_claude_tool_events(&value, &mut uses, &mut results);
    }
    let mut use_counts = BTreeMap::new();
    for tool_use in &uses {
        *use_counts.entry(tool_use.id.clone()).or_insert(0_u32) += 1;
    }
    Ok(uses
        .into_iter()
        .map(|tool_use| {
            let unambiguous_use = use_counts.get(tool_use.id.as_str()) == Some(&1);
            let result = results
                .get(&tool_use.id)
                .filter(|values| values.len() == 1)
                .and_then(|values| values.first());
            HostCommandAttempt {
                command: tool_use.command,
                expected_exit_observed: unambiguous_use
                    && contract.expected_exit_code == 0
                    && result.is_some_and(|value| value.is_error == Some(false)),
                captured_exit_observed: unambiguous_use
                    && result.is_some_and(|value| {
                        output_reports_exit(&value.content, contract.expected_exit_code)
                    }),
                success_marker_observed: unambiguous_use
                    && result.is_some_and(|value| {
                        value.content.contains(&contract.expected_output_contains)
                    }),
            }
        })
        .collect())
}

fn collect_claude_tool_events(
    value: &Value,
    uses: &mut Vec<ClaudeToolUse>,
    results: &mut BTreeMap<String, Vec<ClaudeToolResult>>,
) {
    match value {
        Value::Object(object) => {
            match object.get("type").and_then(Value::as_str) {
                Some("tool_use") if object.get("name").and_then(Value::as_str) == Some("Bash") => {
                    if let (Some(id), Some(command)) = (
                        object.get("id").and_then(Value::as_str),
                        object
                            .get("input")
                            .and_then(|value| value.get("command"))
                            .and_then(Value::as_str),
                    ) {
                        uses.push(ClaudeToolUse {
                            id: id.to_string(),
                            command: command.to_string(),
                        });
                    }
                    return;
                }
                Some("tool_result") => {
                    if let Some(id) = object.get("tool_use_id").and_then(Value::as_str) {
                        let mut content = String::new();
                        if let Some(value) = object.get("content") {
                            collect_text(value, &mut content);
                        }
                        results
                            .entry(id.to_string())
                            .or_default()
                            .push(ClaudeToolResult {
                                is_error: object.get("is_error").and_then(Value::as_bool),
                                content,
                            });
                    }
                    return;
                }
                _ => {}
            }
            for child in object.values() {
                collect_claude_tool_events(child, uses, results);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_claude_tool_events(child, uses, results);
            }
        }
        _ => {}
    }
}

fn collect_text(value: &Value, output: &mut String) {
    match value {
        Value::String(text) => {
            if !output.is_empty() {
                output.push('\n');
            }
            output.push_str(text);
        }
        Value::Object(object) => {
            if object.get("type").and_then(Value::as_str) == Some("text") {
                if let Some(text) = object.get("text").and_then(Value::as_str) {
                    if !output.is_empty() {
                        output.push('\n');
                    }
                    output.push_str(text);
                }
                return;
            }
            for child in object.values() {
                collect_text(child, output);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_text(child, output);
            }
        }
        _ => {}
    }
}

