fn trace_engram_boundary_calls(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
) -> EvalResult<Vec<String>> {
    let reader = BufReader::new(fs::File::open(path)?);
    let mut calls = Vec::new();
    for (index, line) in reader.lines().enumerate() {
        let line = line?;
        if line.trim().is_empty() {
            continue;
        }
        let value: Value = serde_json::from_str(&line).map_err(|error| {
            EvalError::Invalid(format!(
                "invalid {host} JSONL at {} line {}: {error}",
                path.display(),
                index + 1
            ))
        })?;
        collect_engram_boundary_calls(host, &value, evaluation_cwd, &mut calls)?;
    }
    Ok(calls)
}

fn collect_engram_boundary_calls(
    host: &str,
    value: &Value,
    evaluation_cwd: &Path,
    calls: &mut Vec<String>,
) -> EvalResult<()> {
    match host {
        "codex" => {
            let Some(item) = value.get("item") else {
                return Ok(());
            };
            if value.get("type").and_then(Value::as_str) == Some("item.completed")
                && item.get("type").and_then(Value::as_str) == Some("mcp_tool_call")
                && item.get("server").and_then(Value::as_str) == Some("engram")
            {
                let tool = item.get("tool").and_then(Value::as_str).unwrap_or_default();
                let arguments = item.get("arguments").unwrap_or(&Value::Null);
                let call = if tool == "orient"
                    && arguments.get("cwd").and_then(Value::as_str)
                        == Some(evaluation_cwd.to_string_lossy().as_ref())
                {
                    "orient"
                } else if tool == "memory"
                    && is_procedure_match_action(arguments.get("action").and_then(Value::as_str))
                    && memory_call_targets_cwd(arguments, evaluation_cwd)
                {
                    "procedure_match"
                } else {
                    "other"
                };
                calls.push(call.to_string());
            }
        }
        "claude_code" => collect_claude_engram_boundary_calls(value, evaluation_cwd, calls),
        other => {
            return Err(EvalError::Invalid(format!(
                "unsupported host in Engram boundary-order audit: {other}"
            )))
        }
    }
    Ok(())
}

