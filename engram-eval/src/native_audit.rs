fn trace_structured_engram_identity_matches(
    host: &str,
    path: &Path,
    evaluation_cwd: &Path,
    contract: &AcceptanceContract,
) -> EvalResult<bool> {
    if trace_engram_boundary_calls(host, path, evaluation_cwd)?
        != ["orient".to_string(), "procedure_match".to_string()]
    {
        return Ok(false);
    }
    let Some(orientation) = trace_engram_orientation(host, path, evaluation_cwd)? else {
        return Ok(false);
    };
    let Some(identity) = orientation.identity else {
        return Ok(false);
    };
    if !trace_identity_matches(&identity, evaluation_cwd, contract)? {
        return Ok(false);
    }
    let Some(procedure_match) = trace_engram_procedure_match(host, path, evaluation_cwd)? else {
        return Ok(false);
    };
    Ok(procedure_match.identity == identity
        && procedure_match.procedures.is_empty()
        && procedure_match.abstained)
}

