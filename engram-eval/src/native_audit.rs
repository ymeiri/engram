pub(crate) fn shell_commands_from_jsonl(path: &Path) -> EvalResult<Vec<String>> {
    let body = fs::read_to_string(path)?;
    let mut commands = Vec::new();
    for line in body.lines().filter(|line| !line.trim().is_empty()) {
        let value: Value = serde_json::from_str(line)?;
        collect_shell_commands(&value, false, &mut commands);
    }
    Ok(commands)
}

fn collect_shell_commands(value: &Value, shell_context: bool, commands: &mut Vec<String>) {
    match value {
        Value::Object(object) => {
            let local_shell = shell_context
                || object.values().any(|value| {
                    value.as_str().is_some_and(|text| {
                        text.eq_ignore_ascii_case("bash")
                            || text.eq_ignore_ascii_case("shell")
                            || text.eq_ignore_ascii_case("command_execution")
                    })
                });
            if local_shell {
                if let Some(command) = object.get("command").and_then(Value::as_str) {
                    commands.push(command.to_string());
                }
            }
            for child in object.values() {
                collect_shell_commands(child, local_shell, commands);
            }
        }
        Value::Array(values) => {
            for child in values {
                collect_shell_commands(child, shell_context, commands);
            }
        }
        _ => {}
    }
}

struct TreeDigest {
    sha256: String,
    file_count: u64,
    total_bytes: u64,
    earliest_modified_unix_ms: u64,
}

fn digest_path(root: &Path) -> EvalResult<TreeDigest> {
    let mut files = Vec::new();
    collect_regular_files(root, root, &mut files, false)?;
    digest_files(root, files)
}

fn digest_codex_memory_path(root: &Path) -> EvalResult<TreeDigest> {
    let mut files = Vec::new();
    collect_regular_files(root, root, &mut files, true)?;
    digest_files(root, files)
}

fn digest_files(root: &Path, mut files: Vec<PathBuf>) -> EvalResult<TreeDigest> {
    files.sort();
    let mut digest = Sha256::new();
    let mut total_bytes = 0;
    let mut earliest_modified_unix_ms = u64::MAX;
    for relative in &files {
        let path = if root.is_file() {
            root.to_path_buf()
        } else {
            root.join(relative)
        };
        digest.update(relative.to_string_lossy().as_bytes());
        digest.update([0]);
        let mut file = fs::File::open(&path)?;
        let mut buffer = [0_u8; 8192];
        loop {
            let read = file.read(&mut buffer)?;
            if read == 0 {
                break;
            }
            total_bytes += read as u64;
            digest.update(&buffer[..read]);
        }
        digest.update([0xff]);
        earliest_modified_unix_ms = earliest_modified_unix_ms.min(modified_unix_ms(&path)?);
    }
    Ok(TreeDigest {
        sha256: format!("{:x}", digest.finalize()),
        file_count: files.len() as u64,
        total_bytes,
        earliest_modified_unix_ms: if files.is_empty() {
            0
        } else {
            earliest_modified_unix_ms
        },
    })
}

fn collect_regular_files(
    root: &Path,
    path: &Path,
    files: &mut Vec<PathBuf>,
    skip_top_level_git: bool,
) -> EvalResult<()> {
    let metadata = fs::symlink_metadata(path)?;
    if metadata.file_type().is_symlink() {
        return Err(EvalError::Invalid(format!(
            "generated artifact contains a symlink: {}",
            path.display()
        )));
    }
    if metadata.is_file() {
        files.push(
            path.strip_prefix(root)
                .unwrap_or_else(|_| Path::new("artifact"))
                .to_path_buf(),
        );
        return Ok(());
    }
    if !metadata.is_dir() {
        return Err(EvalError::Invalid(format!(
            "generated artifact contains a non-file entry: {}",
            path.display()
        )));
    }
    let mut entries = fs::read_dir(path)?.collect::<Result<Vec<_>, _>>()?;
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        if skip_top_level_git && path == root && entry.file_name() == std::ffi::OsStr::new(".git") {
            continue;
        }
        collect_regular_files(root, &entry.path(), files, skip_top_level_git)?;
    }
    Ok(())
}

fn sha256_file(path: &Path) -> EvalResult<String> {
    let mut digest = Sha256::new();
    let mut file = fs::File::open(path)?;
    let mut buffer = [0_u8; 8192];
    loop {
        let read = file.read(&mut buffer)?;
        if read == 0 {
            break;
        }
        digest.update(&buffer[..read]);
    }
    Ok(format!("{:x}", digest.finalize()))
}

fn modified_unix_ms(path: &Path) -> EvalResult<u64> {
    let modified = fs::metadata(path)?.modified()?;
    system_time_unix_ms(modified)
}

fn system_time_unix_ms(value: SystemTime) -> EvalResult<u64> {
    let duration = value.duration_since(UNIX_EPOCH).map_err(|error| {
        EvalError::Invalid(format!(
            "artifact modification time predates Unix epoch: {error}"
        ))
    })?;
    u64::try_from(duration.as_millis())
        .map_err(|_| EvalError::Invalid("artifact modification time overflow".to_string()))
}

