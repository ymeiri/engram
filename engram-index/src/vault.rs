//! Markdown vault export for Memory OS.
//!
//! This module projects typed memory records into deterministic Markdown files
//! that can be opened in Obsidian or read directly by an agent. It deliberately
//! treats the vault as a generated projection: existing files without the Engram
//! generated marker are skipped instead of overwritten.

use crate::error::{IndexError, IndexResult};
use engram_core::memory::{
    ClaimOrigin, EvidenceKind, KnowledgeCommit, MemoryChangeType, MemoryItem, MemoryScope,
};
use engram_core::repository::{
    GitRepository, LocalCheckout, MonorepoComponent, ProjectRepositoryLink,
};
use serde::{Deserialize, Serialize};
use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Component, Path, PathBuf};
use time::OffsetDateTime;

const GENERATED_BY: &str = "engram-memory-os";
const GENERATED_MARKER: &str = "<!-- engram:generated:file memory-vault-v1 -->";
const VAULT_DIRECTORIES: &[&str] = &[
    "99_System",
    "memory",
    "memory/items",
    "memory/commits",
    "entities",
    "projects",
    "repositories",
];

/// Summary of a vault export operation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryVaultExport {
    /// Vault root path.
    pub root: String,
    /// Files created or updated, relative to root.
    pub files_written: Vec<String>,
    /// Existing files skipped because they were not generated by Engram.
    pub files_skipped: Vec<String>,
    /// Exported memory item count.
    pub memory_item_count: usize,
    /// Exported knowledge commit count.
    pub knowledge_commit_count: usize,
    /// Exported repository page count.
    pub repository_count: usize,
    /// Exported entity page count.
    pub entity_count: usize,
    /// Exported project page count.
    pub project_count: usize,
}

impl MemoryVaultExport {
    /// Number of files written by this export.
    #[must_use]
    pub fn file_count(&self) -> usize {
        self.files_written.len()
    }
}

/// Summary of a vault initialization operation.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryVaultInit {
    /// Vault root path.
    pub root: String,
    /// Directories created, relative to root.
    pub directories_created: Vec<String>,
    /// Directories already present, relative to root.
    pub directories_existing: Vec<String>,
}

/// Read-only status for a generated Memory OS vault.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryVaultStatus {
    /// Vault root path.
    pub root: String,
    /// Whether the root path exists.
    pub exists: bool,
    /// Whether the expected directory skeleton exists.
    pub initialized: bool,
    /// Missing expected directories, relative to root.
    pub missing_directories: Vec<String>,
    /// Number of files under the vault root.
    pub total_file_count: usize,
    /// Number of files containing the Engram generated marker.
    pub generated_file_count: usize,
    /// Number of files not marked as Engram generated files.
    pub user_file_count: usize,
    /// Memory items currently eligible for compilation.
    pub memory_item_count: usize,
    /// Knowledge commits currently eligible for compilation.
    pub knowledge_commit_count: usize,
    /// Repositories currently eligible for compilation.
    pub repository_count: usize,
    /// Entities currently eligible for compilation.
    pub entity_count: usize,
    /// Projects currently eligible for compilation.
    pub project_count: usize,
    /// Files expected from compiling the current store snapshot.
    pub expected_generated_file_count: usize,
}

/// A vault page read from disk.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryVaultPage {
    /// Vault root path.
    pub root: String,
    /// Page path relative to root.
    pub relative_path: String,
    /// Absolute page path.
    pub absolute_path: String,
    /// Whether the page contains the Engram generated marker.
    pub generated: bool,
    /// Page contents.
    pub contents: String,
}

/// Repository topology data included in the vault export.
#[derive(Debug, Clone)]
pub struct RepositoryVaultSnapshot {
    /// Canonical repository.
    pub repository: GitRepository,
    /// Known local checkouts for this repository.
    pub checkouts: Vec<LocalCheckout>,
    /// Registered monorepo components.
    pub components: Vec<MonorepoComponent>,
    /// Project links for the repository.
    pub project_links: Vec<ProjectRepositoryLink>,
}

/// Write a deterministic Markdown vault projection.
pub(crate) fn write_memory_vault(
    root: &Path,
    items: &[MemoryItem],
    commits: &[KnowledgeCommit],
    repositories: &[RepositoryVaultSnapshot],
) -> IndexResult<MemoryVaultExport> {
    fs::create_dir_all(root)?;

    let mut export = MemoryVaultExport {
        root: root.display().to_string(),
        files_written: Vec::new(),
        files_skipped: Vec::new(),
        memory_item_count: items.len(),
        knowledge_commit_count: commits.len(),
        repository_count: repositories.len(),
        entity_count: 0,
        project_count: 0,
    };

    let mut sorted_items = items.to_vec();
    sorted_items.sort_by(|left, right| {
        left.updated_at
            .cmp(&right.updated_at)
            .then_with(|| left.title.cmp(&right.title))
            .then_with(|| left.id.to_string().cmp(&right.id.to_string()))
    });

    let mut sorted_commits = commits.to_vec();
    sorted_commits.sort_by(|left, right| {
        left.created_at
            .cmp(&right.created_at)
            .then_with(|| left.id.to_string().cmp(&right.id.to_string()))
    });

    let mut sorted_repositories = repositories.to_vec();
    sorted_repositories.sort_by(|left, right| {
        left.repository
            .name
            .cmp(&right.repository.name)
            .then_with(|| {
                left.repository
                    .id
                    .to_string()
                    .cmp(&right.repository.id.to_string())
            })
    });

    let entity_names = entity_names(&sorted_items);
    let entity_paths = unique_named_paths(&entity_names, "entities");
    export.entity_count = entity_names.len();

    let project_names = project_names(&sorted_items, &sorted_repositories);
    let project_paths = unique_named_paths(&project_names, "projects");
    export.project_count = project_names.len();

    write_generated_file(
        root,
        Path::new("99_System").join("Vault-Index.md"),
        &vault_index(
            &sorted_items,
            &sorted_commits,
            &sorted_repositories,
            &entity_names,
            &entity_paths,
            &project_names,
            &project_paths,
        ),
        &mut export,
    )?;
    write_generated_file(
        root,
        Path::new("memory").join("index.md"),
        &memory_index(&sorted_items, &sorted_commits),
        &mut export,
    )?;

    for item in &sorted_items {
        write_generated_file(
            root,
            item_relative_path(item),
            &memory_item_page(item),
            &mut export,
        )?;
    }

    for commit in &sorted_commits {
        write_generated_file(
            root,
            commit_relative_path(commit),
            &knowledge_commit_page(commit),
            &mut export,
        )?;
    }

    write_generated_file(
        root,
        Path::new("entities").join("index.md"),
        &entities_index(&entity_names, &entity_paths),
        &mut export,
    )?;
    for entity_name in &entity_names {
        let relative_path = entity_paths.get(entity_name).ok_or_else(|| {
            IndexError::InvalidState(format!("missing vault path for entity: {entity_name}"))
        })?;
        write_generated_file(
            root,
            relative_path.clone(),
            &entity_page(entity_name, &sorted_items),
            &mut export,
        )?;
    }

    write_generated_file(
        root,
        Path::new("repositories").join("index.md"),
        &repositories_index(&sorted_repositories),
        &mut export,
    )?;
    for repository in &sorted_repositories {
        write_generated_file(
            root,
            repository_relative_path(&repository.repository),
            &repository_page(repository),
            &mut export,
        )?;
    }

    for project_name in &project_names {
        let relative_path = project_paths.get(project_name).ok_or_else(|| {
            IndexError::InvalidState(format!("missing vault path for project: {project_name}"))
        })?;
        write_generated_file(
            root,
            relative_path.clone(),
            &project_page(project_name, &sorted_items, &sorted_repositories),
            &mut export,
        )?;
    }

    export.files_written.sort();
    export.files_skipped.sort();
    Ok(export)
}

/// Create the Memory OS vault directory skeleton.
pub(crate) fn init_memory_vault(root: &Path) -> IndexResult<MemoryVaultInit> {
    fs::create_dir_all(root)?;

    let mut init = MemoryVaultInit {
        root: root.display().to_string(),
        directories_created: Vec::new(),
        directories_existing: Vec::new(),
    };

    for directory in VAULT_DIRECTORIES {
        let path = root.join(directory);
        if path.is_dir() {
            init.directories_existing.push((*directory).to_string());
        } else {
            fs::create_dir_all(&path)?;
            init.directories_created.push((*directory).to_string());
        }
    }

    Ok(init)
}

/// Inspect the current vault state without writing any files.
pub(crate) fn inspect_memory_vault(
    root: &Path,
    items: &[MemoryItem],
    commits: &[KnowledgeCommit],
    repositories: &[RepositoryVaultSnapshot],
) -> IndexResult<MemoryVaultStatus> {
    let exists = root.exists();
    let mut missing_directories = Vec::new();
    for directory in VAULT_DIRECTORIES {
        if !root.join(directory).is_dir() {
            missing_directories.push((*directory).to_string());
        }
    }

    let (total_file_count, generated_file_count, user_file_count) = if exists {
        count_vault_files(root)?
    } else {
        (0, 0, 0)
    };
    let entity_count = entity_names(items).len();
    let project_count = project_names(items, repositories).len();
    let expected_generated_file_count = expected_vault_file_count(
        items.len(),
        commits.len(),
        repositories.len(),
        entity_count,
        project_count,
    );

    Ok(MemoryVaultStatus {
        root: root.display().to_string(),
        exists,
        initialized: exists && missing_directories.is_empty(),
        missing_directories,
        total_file_count,
        generated_file_count,
        user_file_count,
        memory_item_count: items.len(),
        knowledge_commit_count: commits.len(),
        repository_count: repositories.len(),
        entity_count,
        project_count,
        expected_generated_file_count,
    })
}

/// Read a page from the vault. The page path must stay inside the vault root.
pub(crate) fn read_memory_vault_page(
    root: &Path,
    page: &str,
) -> IndexResult<Option<MemoryVaultPage>> {
    let mut relative_path = normalize_vault_relative_path(page)?;
    if relative_path.extension().is_none() {
        relative_path.set_extension("md");
    }

    let path = root.join(&relative_path);
    if !path.exists() {
        return Ok(None);
    }
    if !path.is_file() {
        return Err(IndexError::InvalidState(format!(
            "vault page is not a file: {}",
            path.display()
        )));
    }

    let contents = fs::read_to_string(&path)?;
    let generated = contents.contains(GENERATED_MARKER);
    Ok(Some(MemoryVaultPage {
        root: root.display().to_string(),
        relative_path: path_to_markdown(&relative_path),
        absolute_path: path.display().to_string(),
        generated,
        contents,
    }))
}

fn vault_index(
    items: &[MemoryItem],
    commits: &[KnowledgeCommit],
    repositories: &[RepositoryVaultSnapshot],
    entity_names: &BTreeSet<String>,
    entity_paths: &BTreeMap<String, PathBuf>,
    project_names: &BTreeSet<String>,
    project_paths: &BTreeMap<String, PathBuf>,
) -> String {
    let mut output = frontmatter("vault_index", Vec::new());
    output.push_str("# Engram Memory Vault\n\n");
    output.push_str("## Summary\n\n");
    output.push_str(&format!("- Memory items: {}\n", items.len()));
    output.push_str(&format!("- Knowledge commits: {}\n", commits.len()));
    output.push_str(&format!("- Repositories: {}\n", repositories.len()));
    output.push_str(&format!("- Entities: {}\n", entity_names.len()));
    output.push_str(&format!("- Projects: {}\n\n", project_names.len()));

    output.push_str("## Entry Points\n\n");
    output.push_str("- [Memory](../memory/index.md)\n");
    output.push_str("- [Entities](../entities/index.md)\n");
    output.push_str("- [Repositories](../repositories/index.md)\n");
    if !entity_names.is_empty() {
        output.push_str("- Entities\n");
        for entity_name in entity_names {
            if let Some(path) = entity_paths.get(entity_name) {
                output.push_str(&format!(
                    "  - [{}](../{})\n",
                    escape_link_text(entity_name),
                    path_to_markdown(path)
                ));
            }
        }
    }
    if !project_names.is_empty() {
        output.push_str("- Projects\n");
        for project_name in project_names {
            if let Some(path) = project_paths.get(project_name) {
                output.push_str(&format!(
                    "  - [{}](../{})\n",
                    escape_link_text(project_name),
                    path_to_markdown(path)
                ));
            }
        }
    }
    output
}

fn memory_index(items: &[MemoryItem], commits: &[KnowledgeCommit]) -> String {
    let mut output = frontmatter("memory_index", Vec::new());
    output.push_str("# Memory\n\n");
    output.push_str("## Status Counts\n\n");
    for (status, count) in status_counts(items) {
        output.push_str(&format!("- {}: {}\n", status, count));
    }

    output.push_str("\n## Items\n\n");
    for item in items {
        output.push_str(&format!(
            "- [{}](items/{}) - {} - {}\n",
            escape_link_text(&item.title),
            file_name(&item_relative_path(item)),
            item.kind,
            item.status
        ));
    }

    output.push_str("\n## Knowledge Commits\n\n");
    for commit in commits {
        output.push_str(&format!(
            "- [{}](commits/{}) - {} change(s)\n",
            escape_link_text(&commit.message),
            file_name(&commit_relative_path(commit)),
            commit.change_count()
        ));
    }
    output
}

fn memory_item_page(item: &MemoryItem) -> String {
    let mut fields = vec![
        ("engram_id".to_string(), yaml_string(&item.id.to_string())),
        ("kind".to_string(), yaml_string(&item.kind.to_string())),
        ("status".to_string(), yaml_string(&item.status.to_string())),
        (
            "scope_type".to_string(),
            yaml_string(memory_scope_type(&item.scope)),
        ),
        (
            "scope".to_string(),
            yaml_string(&memory_scope_label(&item.scope)),
        ),
        (
            "origin".to_string(),
            yaml_string(&claim_origin_label(&item.origin)),
        ),
        (
            "confidence".to_string(),
            format!("{:.3}", item.confidence.value()),
        ),
        (
            "writer_harness".to_string(),
            yaml_string(&item.writer.harness.to_string()),
        ),
        (
            "writer_model_provider".to_string(),
            yaml_string(&item.writer.model.provider),
        ),
        (
            "writer_model".to_string(),
            yaml_string(&item.writer.model.model),
        ),
        (
            "created_at".to_string(),
            yaml_string(&format_time(item.created_at)),
        ),
        (
            "updated_at".to_string(),
            yaml_string(&format_time(item.updated_at)),
        ),
    ];
    push_optional_field(
        &mut fields,
        "writer_surface",
        item.writer.surface.as_deref(),
    );
    push_optional_field(
        &mut fields,
        "writer_model_version",
        item.writer.model.version.as_deref(),
    );
    if let Some(review_after) = item.review_after {
        fields.push((
            "review_after".to_string(),
            yaml_string(&format_time(review_after)),
        ));
    }

    let mut output = frontmatter("memory_item", fields);
    output.push_str(&format!("# {}\n\n", item.title));
    output.push_str(&item.content);
    output.push_str("\n\n## Metadata\n\n");
    output.push_str(&format!("- Kind: {}\n", item.kind));
    output.push_str(&format!("- Status: {}\n", item.status));
    output.push_str(&format!("- Scope: {}\n", memory_scope_label(&item.scope)));
    output.push_str(&format!("- Origin: {}\n", claim_origin_label(&item.origin)));
    output.push_str(&format!("- Confidence: {:.3}\n", item.confidence.value()));
    output.push_str(&format!(
        "- Writer: {} / {} / {}\n",
        item.writer.harness, item.writer.model.provider, item.writer.model.model
    ));
    if !item.tags.is_empty() {
        output.push_str(&format!("- Tags: {}\n", item.tags.join(", ")));
    }
    if !item.supersedes.is_empty() {
        output.push_str("- Supersedes:\n");
        for id in &item.supersedes {
            output.push_str(&format!("  - {}\n", id));
        }
    }

    output.push_str("\n## Evidence\n\n");
    if item.evidence.is_empty() {
        output.push_str("No evidence recorded.\n");
    } else {
        for evidence in &item.evidence {
            output.push_str(&format!(
                "- {}: {}",
                evidence_kind_label(&evidence.kind),
                evidence.target
            ));
            if let Some(summary) = &evidence.summary {
                output.push_str(&format!(" - {}", summary));
            }
            output.push('\n');
            if let Some(excerpt) = &evidence.excerpt {
                output.push_str(&format!("  - Excerpt: {}\n", excerpt));
            }
        }
    }

    output
}

fn knowledge_commit_page(commit: &KnowledgeCommit) -> String {
    let fields = vec![
        ("engram_id".to_string(), yaml_string(&commit.id.to_string())),
        ("message".to_string(), yaml_string(&commit.message)),
        (
            "writer_harness".to_string(),
            yaml_string(&commit.writer.harness.to_string()),
        ),
        (
            "writer_model".to_string(),
            yaml_string(&commit.writer.model.model),
        ),
        (
            "created_at".to_string(),
            yaml_string(&format_time(commit.created_at)),
        ),
    ];

    let mut output = frontmatter("knowledge_commit", fields);
    output.push_str(&format!("# {}\n\n", commit.message));
    output.push_str("## Commit\n\n");
    output.push_str(&format!("- ID: {}\n", commit.id));
    if let Some(parent_id) = commit.parent_id {
        output.push_str(&format!("- Parent: {}\n", parent_id));
    }
    if let Some(session_id) = commit.session_id {
        output.push_str(&format!("- Session: {}\n", session_id));
    }
    output.push_str(&format!(
        "- Writer: {} / {} / {}\n",
        commit.writer.harness, commit.writer.model.provider, commit.writer.model.model
    ));

    output.push_str("\n## Changes\n\n");
    if commit.changes.is_empty() {
        output.push_str("No changes recorded.\n");
    } else {
        for change in &commit.changes {
            output.push_str(&format!(
                "- {}: {} - {}\n",
                memory_change_type_label(change.change_type),
                change.title,
                change.summary
            ));
            if let Some(item_id) = change.item_id {
                output.push_str(&format!("  - Item: {}\n", item_id));
            }
            if change.before_hash.is_some() || change.after_hash.is_some() {
                output.push_str(&format!(
                    "  - Hash: {} -> {}\n",
                    change.before_hash.as_deref().unwrap_or("unknown"),
                    change.after_hash.as_deref().unwrap_or("unknown")
                ));
            }
        }
    }
    output
}

fn repositories_index(repositories: &[RepositoryVaultSnapshot]) -> String {
    let mut output = frontmatter("repositories_index", Vec::new());
    output.push_str("# Repositories\n\n");
    if repositories.is_empty() {
        output.push_str("No repositories registered.\n");
    } else {
        for snapshot in repositories {
            output.push_str(&format!(
                "- [{}]({})",
                escape_link_text(&snapshot.repository.name),
                file_name(&repository_relative_path(&snapshot.repository))
            ));
            if let Some(remote_url) = &snapshot.repository.remote_url {
                output.push_str(&format!(" - {}", remote_url));
            }
            output.push('\n');
        }
    }
    output
}

fn entities_index(
    entity_names: &BTreeSet<String>,
    entity_paths: &BTreeMap<String, PathBuf>,
) -> String {
    let mut output = frontmatter("entities_index", Vec::new());
    output.push_str("# Entities\n\n");
    if entity_names.is_empty() {
        output.push_str("No entity-scoped memory items exported.\n");
    } else {
        for entity_name in entity_names {
            if let Some(path) = entity_paths.get(entity_name) {
                output.push_str(&format!(
                    "- [{}]({})\n",
                    escape_link_text(entity_name),
                    path_to_markdown_without_prefix(path, "entities")
                ));
            }
        }
    }
    output
}

fn entity_page(entity_name: &str, items: &[MemoryItem]) -> String {
    let fields = vec![("entity_name".to_string(), yaml_string(entity_name))];
    let mut output = frontmatter("entity", fields);
    output.push_str(&format!("# Entity: {}\n\n", entity_name));

    output.push_str("## Memory Items\n\n");
    let entity_items: Vec<_> = items
        .iter()
        .filter(|item| memory_scope_entity_name(&item.scope) == Some(entity_name))
        .collect();
    if entity_items.is_empty() {
        output.push_str("No entity-scoped memory items exported.\n");
    } else {
        for item in entity_items {
            output.push_str(&format!(
                "- [{}](../../{}) - {} - {}\n",
                escape_link_text(&item.title),
                path_to_markdown(&item_relative_path(item)),
                item.kind,
                item.status
            ));
        }
    }

    output
}

fn repository_page(snapshot: &RepositoryVaultSnapshot) -> String {
    let repository = &snapshot.repository;
    let fields = vec![
        (
            "engram_id".to_string(),
            yaml_string(&repository.id.to_string()),
        ),
        ("repository_name".to_string(), yaml_string(&repository.name)),
        (
            "provider".to_string(),
            yaml_string(&repository.provider.to_string()),
        ),
    ];
    let mut output = frontmatter("repository", fields);
    output.push_str(&format!("# Repository: {}\n\n", repository.name));

    output.push_str("## Source\n\n");
    output.push_str(&format!("- ID: {}\n", repository.id));
    output.push_str(&format!("- Provider: {}\n", repository.provider));
    if let Some(remote_url) = &repository.remote_url {
        output.push_str(&format!("- Remote: {}\n", remote_url));
    }
    if let Some(default_branch) = &repository.default_branch {
        output.push_str(&format!("- Default branch: {}\n", default_branch));
    }
    if let Some(description) = &repository.description {
        output.push_str(&format!("- Description: {}\n", description));
    }

    output.push_str("\n## Local Checkouts\n\n");
    if snapshot.checkouts.is_empty() {
        output.push_str("No local checkouts registered.\n");
    } else {
        for checkout in &snapshot.checkouts {
            output.push_str(&format!("- {}\n", checkout.local_path));
            if let Some(branch) = &checkout.current_branch {
                output.push_str(&format!("  - Branch: {}\n", branch));
            }
            if let Some(head_sha) = &checkout.head_sha {
                output.push_str(&format!("  - HEAD: {}\n", head_sha));
            }
            if let Some(is_dirty) = checkout.is_dirty {
                output.push_str(&format!("  - Dirty: {}\n", is_dirty));
            }
        }
    }

    output.push_str("\n## Project Links\n\n");
    if snapshot.project_links.is_empty() {
        output.push_str("No project links registered.\n");
    } else {
        for link in &snapshot.project_links {
            output.push_str(&format!("- {} ({})", link.project_name, link.role));
            if let Some(component_path) = &link.component_path {
                output.push_str(&format!(" - component: {}", component_path));
            }
            output.push('\n');
        }
    }

    output.push_str("\n## Components\n\n");
    if snapshot.components.is_empty() {
        output.push_str("No monorepo components registered.\n");
    } else {
        for component in &snapshot.components {
            output.push_str(&format!("- {} ({})", component.name, component.path));
            if let Some(kind) = &component.kind {
                output.push_str(&format!(" - {}", kind));
            }
            if let Some(description) = &component.description {
                output.push_str(&format!(" - {}", description));
            }
            output.push('\n');
        }
    }

    output
}

fn project_page(
    project_name: &str,
    items: &[MemoryItem],
    repositories: &[RepositoryVaultSnapshot],
) -> String {
    let fields = vec![("project_name".to_string(), yaml_string(project_name))];
    let mut output = frontmatter("project", fields);
    output.push_str(&format!("# Project: {}\n\n", project_name));

    output.push_str("## Memory Items\n\n");
    let project_items: Vec<_> = items
        .iter()
        .filter(|item| memory_scope_project_name(&item.scope) == Some(project_name))
        .collect();
    if project_items.is_empty() {
        output.push_str("No project-scoped memory items exported.\n");
    } else {
        for item in project_items {
            output.push_str(&format!(
                "- [{}](../../{}) - {} - {}\n",
                escape_link_text(&item.title),
                path_to_markdown(&item_relative_path(item)),
                item.kind,
                item.status
            ));
        }
    }

    output.push_str("\n## Repositories\n\n");
    let mut wrote_repository = false;
    for snapshot in repositories {
        let links: Vec<_> = snapshot
            .project_links
            .iter()
            .filter(|link| link.project_name.eq_ignore_ascii_case(project_name))
            .collect();
        if links.is_empty() {
            continue;
        }
        wrote_repository = true;
        output.push_str(&format!(
            "- [{}](../../{})\n",
            escape_link_text(&snapshot.repository.name),
            path_to_markdown(&repository_relative_path(&snapshot.repository))
        ));
        for link in links {
            output.push_str(&format!("  - Role: {}", link.role));
            if let Some(component_path) = &link.component_path {
                output.push_str(&format!("; component: {}", component_path));
            }
            output.push('\n');
        }
    }
    if !wrote_repository {
        output.push_str("No repositories linked to this project.\n");
    }

    output
}

